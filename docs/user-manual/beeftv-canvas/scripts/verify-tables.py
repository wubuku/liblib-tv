"""第八道闸：markdown 表格结构核对。

**⚠️ Batch 246 订正：本文原先自称「第七道闸」，而闸号是照 `AUDIT-RULES.md` 的
「闸 → 反验对应关系」表量的——那一行写着「8 表格结构」。自称与登记不一致时，
登记那一侧是事实（本批两处脚本头都写着第七道闸，错的却是它们）。**

背景（Batch 142）：修一批否定式断言时，撞见 `PROGRESS.md` 里 **5 行表格被代码里的
`||` 截断**（Batch 122 / 124 / 135 / 136 / 102）。markdown 表格里，**单元格内部的裸竖线
会多切出一列**，那几行渲染出来是错位的——而它们**已经错了好几个批次没人发现**，
因为前六道闸都不看表格结构。

**这类损坏和 Batch 135「不可达声明悄悄过期」是同一类风险**：它不会让构建失败，
只会让读账本的人看到错位的内容，而且**越是内容里带代码的行越容易中招**
（`a || b`、`x ? y : z` 这类写法天然含竖线）。

判据（对**全部** .md，含内部资料——损坏恰恰出在内部资料里，发布页当时是干净的）：
  1. 跳过围栏代码块（``` / ~~~）内的内容：那里的竖线不是表格；
  2. 连续成块的 `|` 开头行算一张表；
  3. 块内**每一行的解析格数**不得超过表头格数；
  4. 块有两行以上时，第二行必须是 GFM 分隔行，**且格数与表头相同**。

═══════════════════════════════════════════════════════════════════════════
**Batch 246：判据 3/4 原来比的是「未转义竖线数」，而 GFM 比的是「解析出的格数」。
两者只在「每行行尾竖线配置相同」时等价——这个不等价同时造出了漏报和误报。**
═══════════════════════════════════════════════════════════════════════════

本闸原先有三条**从未被核对过**的依据，全部是写在注释里的断言。本批把它们
送过 vitepress 1.6.4 的真渲染器逐条量，结论如下（**下表是实测，不是推的**）：

| 形态                                                | 真渲染结果            |
|-----------------------------------------------------|-----------------------|
| 首尾竖线**都**可省（`A | B` + `--- | ---`）         | 是表格                |
| 表头缺行尾竖线                                        | **是表格**            |
| 分隔行缺行尾竖线                                      | **是表格**            |
| 数据行缺行尾竖线                                      | **是表格**            |
| 分隔行格数 ≠ 表头格数（**双向**：多和少都算）           | **整块不是表格**      |
| 分隔格里混进字母 / 用 `=`                            | 整块不是表格          |
| 数据行多一格                                          | 仍是表格，**多出的格被静默丢弃** |
| 数据行少一格                                          | 补空单元格            |

据此改掉三处：

  (1) **「以未转义竖线结尾是 GFM 表格行的规范形态」——假的。**
      上表第 2/3/4 行：行尾竖线在**表头、分隔行、数据行上都可以省**，
      少了照样是表格。原注释里「规范形态」四个字没有依据。
      **连带后果（实测）**：`| A | B |` 配 `|---|---|`（格数相同、只是分隔行省了行尾竖线）
      是一张**完全正常**的两列表，而旧闸会同时报出**两条**诊断：
      「它不是分隔行：GFM 不会把这块当表格」与「行尾没有竖线」。
      **两条都是假的，照着改会把一张好表改坏。**

  (2) **「少一个结构竖线 → GFM 少切一列」——不准确。**
      少的那一列由 GFM **补空单元格**，不是消失；而表头/分隔行少一格
      换来的后果也不是「少一列」，是**整块不再是表格**。
      真正让「少一个结构竖线 + 多一个字面竖线」变成损坏的，
      是**多出来的那一格**（内容被静默丢弃），不是少的那一个。

  (3) **「多一个字面竖线 → 一行凭空多出一列」——假的。**
      实测多出的那格**被静默丢弃**：表格仍是 3 列，第 4 格内容读者看不到。
      **危害是真的（内容丢失），机制说错了**（不是多一列）。

**为什么 (1) 那个方向要整个删掉，而不是收窄**：
`ends_with_pipe` 抓的形态（上表 2/3/4 行）**渲染器全都接受**，
而它当初要抓的真缺陷——「少一个结构竖线 + 多一个字面竖线在计数上互相抵消」——
**已被新的格数比较接住**（那条注入现在多出的是一格，格数比较直接抓到）。
按 Batch 243 的判据：**注释描述的条件比代码宽、且宽出来的那一段在账本上有明确含义**，
这里是反过来——**判据抓的形态实测无害**，所以删掉方向，而不是给它换个说法留着。
Batch 206 的反验用例 6 已改为证明新方向接住了同一个缺陷。

═══════════════════════════════════════════════════════════════════════════
**本闸已知且不覆盖的边界（写下来，而不是留在代码里当免责）**
═══════════════════════════════════════════════════════════════════════════
  * **表块只按「行首是 `|`」来认定**（判据 2）。GFM 不要求行首竖线，
    实测 `A | B | C |` + `|---|---|` + `甲 | 乙 | 丙 |` 也**不是**表格，
    而写成这样的一张表在旧闸眼里是 **3 个互不相干的单行块**，rc=0。
    本树 41 个文件、261 段表块全部是 `|` 开头形态，但这是本树的写法，
    **不是本闸的保证**。要覆盖它得先解决「怎么把正文行和表头区分开」，
    那不是改一行判据的事。
  * 判据 3 只管「多」，不管「少」——少格由 GFM 补空、渲染正常，
    而账本语义上的缺登记由**闸 19** 在同批接管（分工是量出来的）。

未转义竖线的判定是**前面不是反斜杠**。因此代码段里的 `||` 必须写成 `\\|\\|`，
单元格里的 URL 含 `|` 也要转义。

为什么单列一道闸而不是塞进 build-site 的内联检查：
  前六道闸查的是**内容对不对**（引用、端点、标签、断言），这一道查的是**结构坏没坏**——
  坏掉的表格会让前六道闸读到的内容本身就是错位的，属于它们的前置条件。

退出码：0 全部表格结构一致；1 有行与所在表的结构不符；2 一个文件都没查到。
"""

import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
from tablerow import UNESCAPED_SPLIT  # noqa: E402
MANUAL = os.path.dirname(ROOT)


#: GFM 分隔行的**每一格**必须长这样（Batch 213 实测，与 GFM 一致：零例外）。
_DELIM_CELL = re.compile(r"^:?-+:?$")

#: 按**未转义**竖线切。`(?<!\\)` 的意思是「前面不是反斜杠」——转义竖线是单元格内容的一部分。
#: **Batch 256：这一份是收敛来的**——收敛前本文件、`verify-batch-rows.py` 与 `selftest-batch-rows.py` 各有一份，
#: **理由与边界见 `tablerow.py` 的文件头**。
_UNESCAPED_SPLIT = UNESCAPED_SPLIT


def cells(line):
    """按 **GFM 的解析规则**返回这一行的单元格列表（Batch 246 新增）。

    规则就四步，与真渲染器逐条对齐（vitepress 1.6.4 实测）：

      1. **去掉行首行尾空白**（实测：分隔行末尾一个空格不影响它被当成表格；
         `AUDIT.md` 里 11 处表**缩进在列表里**、前面有两个空格，那两个空格
         同样不是单元格内容——第一次写漏了这一步，闸 7 把 11 张好表报成了坏表）；
      2. **剥掉可选的行首 `|`**；
      3. **剥掉可选的行尾未转义 `|`**；
      4. 按**未转义**竖线切。

    **为什么必须数「格」而不是数「竖线」（Batch 246 的全部修法都在这一句）**：
    竖线数与格数只差「行首 1 个 + 行尾 0 或 1 个」，**而那 0 或 1 逐行不同**。
    实测两侧都出事：

      · `| A | B |`（3 竖线 / 2 格）配 `|---|---|`（2 竖线 / 2 格）——**是表格**，
        但按竖线数比是 3≠2，旧闸**误报**「它不是分隔行，整块会被原样显示」；
      · 表头 3 格而分隔行 2 格时，**竖线数可以恰好相等**（首尾配置不同时），
        按竖线数比会**漏报**整块不是表格的真缺陷。

    数格数之后，「多一格」也和真渲染器对齐了：GFM 不会凭空多出一列，
    它**把多出来的那一格静默丢弃**（内容丢失）——危害不变，机制说准了。
    """
    t = line.strip()
    if not t:
        return []
    if t[0] == "|":
        t = t[1:]
    if t and t[-1] == "|" and (len(t) < 2 or t[-2] != "\\"):
        t = t[:-1]
    return _UNESCAPED_SPLIT.split(t)


def cell_count(line):
    """这一行解析出几格（**不是**数竖线——见 `cells` 的说明）。"""
    return len(cells(line))


def is_separator(line):
    """宽松版：这一行**看起来**像不像分隔行（字符集 + 至少一个 `-`）。

    它是 Batch 174 判「单行块」用的，问的是「像不像」；
    `is_real_delimiter` 问的是「GFM 会不会真的把它当分隔行」——
    **两种问法回答的不是同一个问题，所以两种都留着。**
    """
    s = line.strip()
    return bool(s) and set(s) <= set("|-: ") and "-" in s


def is_real_delimiter(line, header_cells):
    """这一行是不是 GFM 意义上的分隔行，**且格数与表头相同**。

    **Batch 246：比的是格数，不再是竖线数。** 实测依据见 `cells` 的说明
    （旧口径同时造出误报与漏报）。每格必须匹配 `^:?-+:?$` 这一半是
    Batch 213 加的，本批复测**六种形态全对、零例外**（`-+` 一格也认、
    `:---` / `---:` / `:---:` 都认、混字母或用 `=` 一律不认），**保留**。
    """
    c = cells(line)
    if len(c) != header_cells:
        return False
    return all(_DELIM_CELL.match(x.strip()) for x in c)


def scan(path):
    """返回 [(行号, 该行格数, 表头格数, 行首摘录)]。"""
    try:
        with io.open(path, "r", encoding="utf-8") as f:
            lines = f.read().split("\n")
    except (IOError, UnicodeDecodeError):
        return []

    problems = []
    sep_problems = []           # **第二行不是合法分隔行**（Batch 213，Batch 246 改口径）
    fence = None
    block = []  # [(行号, 原始行)]

    def flush():
        if not block:
            return
        header_cells = cell_count(block[0][1])
        # ⚠️ Batch 174 新增：**块只有一行、且那一行不是分隔行** = 畸形表。
        # GFM 要求「表头 + 分隔行」相邻才算表格；一旦中间被空行或引用块隔开，
        # **整块会被当成普通段落原样显示**——不报错、不截断，只是**表格消失了**。
        # 本闸原先只比「同一块内各行的列数」，而畸形表在它眼里是「一个 1 行的块」，
        # 列数自然一致，**于是完全看不见**。
        # 真实案例两处：`20-reference.md` 的 `/dev/folders` 那一行被空行隔在路由表之外
        # （**读者看到的是一行悬空的表格文字**），以及小节标题里手写的「策略项」表头
        # 与 `|---|` 之间夹进了引用块——后者是本批自己写坏的，当场被这条判据抓住。
        if len(block) == 1 and not is_separator(block[0][1]):
            problems.append((block[0][0], header_cells, header_cells,
                             block[0][1].strip()[:70] + "  ← 单行且不是分隔行"))
            block.clear()
            return
        # **Batch 213：块有两行以上时，第二行必须是 GFM 意义上的分隔行。**
        # **实测漏报面**（量出来的，不是推的）：在 PROGRESS.md 那张批次表上注入五种损坏，
        # **五种里有五种闸 8 报绿**——删掉整条分隔行 / 分隔行少一列 / 分隔行写成 `| |` /
        # 分隔行缺首尾竖线 / 分隔行被空行隔开。
        # **五种是同一个根因**：本闸把「连续的 `|` 行」当成表，
        # **却从不问第二行是不是分隔行**——
        # 而 **GFM 里没有分隔行的 `|` 行块根本不是表格，它会被原样当普通文本显示**。
        # **这正是本闸存在的意义那一类**（Batch 142 的原话）：
        # 不让构建失败，只让人看到错位的内容。
        # **假阳性实测**：全树 261 段非围栏的 `|` 行块里，被这条判据报出来的只有 1 段，
        # **而那一段是真缺陷**（见下）。
        if len(block) >= 2 and not is_real_delimiter(block[1][1], header_cells):
            sep_problems.append(
                (block[1][0], cell_count(block[1][1]), header_cells,
                 block[1][1].strip()[:70]
                 + "  ← 它的上一行是表头，而**它不是分隔行**："
                   "GFM 不会把这块当表格，整块会被原样显示成普通文本"))
        for lineno, raw in block:
            n = cell_count(raw)
            # 多于表头 = 多一格 = GFM **静默丢弃**多出来的那格 = 内容丢失 = 损坏。
            # 少于表头由 GFM 补空，渲染正常，本闸不管（账本语义由闸 19 接管）。
            if n > header_cells:
                problems.append((lineno, n, header_cells, raw.strip()[:70]))
        block.clear()

    for idx, line in enumerate(lines, 1):
        m = re.match(r"^\s*(`{3,}|~{3,})", line)
        if m:
            mark = m.group(1)[0]
            if fence is None:
                fence = mark
            elif fence == mark:
                fence = None
            flush()
            continue
        if fence is not None:
            continue
        if line.lstrip().startswith("|"):
            block.append((idx, line))
        else:
            flush()
    flush()
    return sep_problems + problems


def main():
    root = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else MANUAL
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames
                       if d not in (".vitepress", "node_modules", ".git", "dist")]
        for name in filenames:
            if name.endswith(".md"):
                files.append(os.path.join(dirpath, name))
    files.sort()

    total_bad = 0
    checked = 0
    for path in files:
        problems = scan(path)
        checked += 1
        if not problems:
            continue
        rel = os.path.relpath(path, root)
        print(f"  ✗ {rel}：{len(problems)} 处表格结构问题")
        for lineno, n, header_n, excerpt in problems:
            if excerpt.endswith("← 单行且不是分隔行"):
                # 这类不是「列数不符」，是**整张表不会被渲染成表格**（Batch 174）
                print(f"      第 {lineno} 行：这一行没有和分隔行相邻，"
                      f"**整块不会被渲染成表格**（GFM 要求表头与分隔行紧挨着）| "
                      f"{excerpt.rsplit('  ←', 1)[0]}")
            else:
                print(f"      第 {lineno} 行：解析出 {n} 格，表头是 {header_n} 格 | {excerpt}")
        total_bad += len(problems)

    if total_bad:
        print(f"表格结构核对：{total_bad} 行异常（{checked} 个文件）")
        print("  → 单元格内的竖线必须转义成 \\| （代码段里的 `||` 写成 `\\|\\|`）")
        return 1
    # **零输入不许报绿**（Batch 191 纪律 156 + Batch 192 实测）。
    # 实测本闸在一棵**空手册树**上原样输出「表格结构核对：**0 个文件**、全部表格行列数一致」
    # 并 rc=0——**「一个文件都没检查」和「全部文件都合格」在退出码与措辞上都一样**，
    # 而前者读起来像好消息。它躲过 25 道闸的原因很朴素：**它核的东西是 .md 文件，
    # 而空树里没有 .md**，于是任何「先读文件再核」的判据都会空转。
    if checked == 0:
        print("[未能核对] 一个 .md 文件都没找到——本闸本轮什么也没检查，"
              "**不能按「全部表格都没问题」通过**")
        return 2
    print(f"表格结构核对：{checked} 个文件、全部表格结构一致")
    return 0


if __name__ == "__main__":
    sys.exit(main())
