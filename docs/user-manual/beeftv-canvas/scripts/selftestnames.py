"""**「一个 `scripts/` 文件是不是注入夹具」只有一份判据**（Batch 258 新增）。

**这个模块存在的理由是一次普查**（不是一次事故）：
Batch 256 把全树的正则字面量普查了一遍，跨文件重复里有这么一条——
`^selftest-(?:[a-z0-9]+-)?fix-[a-z0-9]+-` **逐字出现在两个闸里**
（`verify-meta.py` 与 `verify-selftest-bootable.py`，各一份 `FIXTURE_RE`），
**而它原先是白纸黑字写着「故意复制而不共用」的**：

> 与闸 18 的 `FIXTURE_RE` 逐字相同，但故意复制而不共用——
> 闸之间互相 import 会让任一方坏掉时另一方跟着起不来，
> **而那正是 Batch 178 记下的那次失效**。

**那个理由在写下它的当天就成立，而它现在已经过期了**，过期原因有两条：

**一、Batch 178 那次失效的真正成因已经有机器管着了。**
当时 4 份反验只搬了被测闸与 `baseline.py`，于是临时目录里 `ModuleNotFoundError`，
**而 `build-site.sh` 仍然全绿**。**闸之间的 import 本身从来不是问题，
「搬的时候漏了那个模块」才是**——
而 Batch 253 建的 `stagedeps.stage_gate()` 正是把「该搬哪些」从人记变成算出来的，
**闸 17 则核「每份反验搬的闸，其本地依赖闭包齐不齐」**。
**换句话说：为了防那次失效而拒绝 import，代价正是让那次失效有可能重演。**

**二、本项目已经有四份闸在 import 共享模块了**（Batch 256 的 `tablerow.py`），
**而那四份的输出在收敛前后逐字节不变**——
**「闸 import 共享模块会出事」这件事在这里已经被实测证伪过一次。**

**所以本模块只做一件事：把这条判据收到一处，并保留两处原有的名字**
（`FIXTURE_RE`），**让调用方那一行不用改**——
**收敛的目标是「一份实现」，不是「让 diff 看起来大」。**

**纪律 274：共享概念只能有一份实现。**
**而「同一件事被手写几遍，就会有几套判真条件」**——
Batch 252 改闸 5 的表格行判据时，那正是危险动作。

**刻意不在这里的东西**：**「是不是一个 `selftest-*`」与「是不是一个 `.py`/`.sh`」**
仍留在各闸自己手里——**那两件事问的不是同一个问题**，
而 `tablerow.py` 那次刻意没合并 `verify-exclusions.py` 的判据是同一个道理
（纪律 283 推论：共享 ≠ 沾边就合）。
"""

import re

#: 注入夹具的判据：**文件名里的 `fix-` 中段**。
#: **Batch 258 从两个闸各一份收敛到此处**（原先逐字相同，且被注释标注为
#: 「故意复制而不共用」——**而那个理由已经被 `stagedeps` 与 `tablerow.py` 作废**）。
FIXTURE_RE = re.compile(r"^selftest-(?:[a-z0-9]+-)?fix-[a-z0-9]+-")


def is_fixture(name):
    """这个 `scripts/` 下的文件名是不是一个**注入夹具**。

    **两处调用方问的确实是同一件事**（纪律 109：分类判据要锚可观测事实，
    **而这里可观测的事实就是文件名里的 `fix-`**），
    **所以给一个语义明确的名字，让「为什么共用」写在一处而不是两处**。
    """
    return bool(FIXTURE_RE.match(name))
