import os
import re
import sys

from headingkey import atx_level, rendered_key, strip_fenced

CONTENT_PAGES = ("00-quickstart.md", "20-reference.md", "30-concepts.md", "90-troubleshooting.md")

# 扫到的标题数量下限。**低于它就报「未能核对」，不许报「通过」**（纪律 156）。
# 真实值 379，取 100 留足余量，又足以抓住「页面集合写错 / 扫空」这类整片失效。
MIN_HEADINGS = 100


def content_pages(root):
    """手册的正文页（与闸 26 / 27 / 28 同一套范围口径）。"""
    out = []
    for base in CONTENT_PAGES:
        p = os.path.join(root, base)
        if os.path.isfile(p):
            out.append(p)
    task_dir = os.path.join(root, "10-tasks")
    if os.path.isdir(task_dir):
        for name in sorted(os.listdir(task_dir)):
            if name.endswith(".md"):
                out.append(os.path.join(task_dir, name))
    return out


def check_page(path, rel):
    """返回该页的 (同名标题列表, 跳级列表, H1 数量, 标题总数)。"""
    body = strip_fenced(open(path, encoding="utf-8", errors="ignore").read())
    headings = []
    for lineno, line in enumerate(body.split("\n"), 1):
        # **Batch 248 换掉认标题的办法**：原来用 `re.match(r"^(#{1,6})\s+(.*)$", line)`，
        # 而 Python 的 `\s` **也匹配全角空格**。实测 `#　全角空格标题` 被认成 h1，
        # **而真渲染器给出的是零个标题**——写两个这样的行，闸会报「同名标题」＋「两个 H1」，
        # **凭空造出两处缺陷，而页面上一个标题都没有。** CommonMark 的 ATX 开头
        # 只认 U+0020 / U+0009，判据也只该认这两个。
        #
        # **Batch 251：级别也改由 `atx_level` 给**（Batch 248 只换了「是不是标题」，
        # 级别还留在 `len(line) - len(line.lstrip("#"))`——**而那正是同一处的第四份实现**）。
        # 实测它在缩进标题上算出 **0**：`  # 又一个 H1` 的行首是空格，
        # `lstrip("#")` 一个字符都去不掉，于是 `len(line) - len(line) = 0`。
        # **后果是两条判据同时失效**：判「唯一 H1」数不到它（0 ≠ 1）、
        # 判「层级跳级」也因为 `0 > prev + 1` 为假而放行它。
        # **而渲染器给的是货真价实的 `<h1>`。**
        lv = atx_level(line)
        if lv is not None:
            headings.append((lv, rendered_key(line), lineno))

    dups = []
    seen = {}
    for _level, name, lineno in headings:
        # **同名按【渲染后的标题文字】判，而不是按源码里的原始行。**
        # 真渲染器认的是那个文字，判据 Batch 245 订正后的理由也是
        # 「目录上两个逐字相同的条目」——**而它拿原始行当键，问的就不是那一件事。**
        # 实测三处漏报（真渲染器都判它们同名、slug 去重成 `-1`）：
        #   `## 相关页面 ##` 与 `## 相关页面`；`## [相关页面](x.md)` 与 `## 相关页面`；
        #   `## 用 \`npm\` 安装` 与 `## 用 npm 安装`。
        # **归一化规则与它的一致率是被量过的，不是照着 CommonMark 抄的**——
        # 见 `headingkey.py` 的文件头：两批共 45 种形态一致率 100%（Batch 251 补测 30 种，
        # **补上了那 45 种里缺的缩进标题与空标题**）。
        if name in seen:
            dups.append((name, seen[name], lineno))
        else:
            seen[name] = lineno
    # 跳级：按文档顺序，某一级的标题前面没有它的直接上一级
    jumps = []
    prev = 0
    for level, name, lineno in headings:
        if prev and level > prev + 1:
            jumps.append((prev, level, name, lineno))
        prev = level
    h1 = [ln for lvl, _n, ln in headings if lvl == 1]
    return dups, jumps, h1, len(headings)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    pages = content_pages(root)
    if len(pages) < 10:
        print(f"[未能核对] 只找到 {len(pages)} 个正文页（下限 10），输入范围明显不对")
        return 2

    problems = []
    total = 0
    for page in pages:
        rel = os.path.relpath(page, root)
        dups, jumps, h1, n = check_page(page, rel)
        total += n
        for name, first, second in dups:
            # **⚠️ Batch 247 订正这条报错文案**：它原先写的是
            # 「VitePress 给同名标题生成**同一个锚点**，页内目录里后一个的跳转会落到前一个」，
            # **而那句话在 Batch 245 已被实测证伪**（`slugify` 会去重，第二个拿到 `-1`）。
            # **Batch 245 订正了脚本头、风险表、清单表和纪律 250，唯独漏了这一处**——
            # **而这一处恰恰是判据真正打印给用户看的那一句**（纪律 246/247/248：
            # 判据不只是发现问题的工具，它还是指示动作的说明书）。
            # **照着旧文案去查「锚点撞车」会查一个不存在的东西。**
            problems.append(
                f"{rel}:{second} 标题「{name}」与第 {first} 行同名"
                f"——**这不是锚点撞车**（VitePress 的 slugify 会去重，后一个拿到 "
                f"`-1`，href 各自指向自己）；"
                f"仍然要改的理由有两条：页内目录上会出现**两个逐字相同、无法区分的条目**，"
                f"而同名标题多半是同一节被复制了两遍"
            )
        for prev, level, name, lineno in jumps:
            problems.append(
                f"{rel}:{lineno} 从 h{prev} 跳到 h{level}（{name}）——"
                f"中间那一级在页内不存在，页内目录里它成了别人的子项"
            )
        if len(h1) != 1:
            problems.append(f"{rel}：全文有 {len(h1)} 个 H1（应为 1）")

    if total < MIN_HEADINGS:
        print(f"[未能核对] 只扫到 {total} 个标题（下限 {MIN_HEADINGS}，读了 {len(pages)} 个正文页）"
              f"——本闸本轮什么也没检查，**不能按「标题都没问题」通过**")
        return 2

    if problems:
        print(f"页内标题核对：{len(pages)} 个正文页、{total} 个标题，{len(problems)} 处问题")
        for x in problems:
            print("  ✗ " + x)
        print("  → 同名标题改掉其中一个；跳级的那一级要么补上、要么改成紧邻的上一级")
        return 1

    print(f"页内标题核对：{len(pages)} 个正文页、{total} 个标题，"
          f"页内无同名标题、层级无跳级、每页恰好一个 H1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
