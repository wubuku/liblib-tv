import sys
# 方向九反验用例 26：给覆盖度表**新增一道闸的 A 类行**（A 类比闸门清单多 1 行）
# → 期望方向九报出「覆盖度表与闸门清单脱节」。
#
# **这条是方向九最核心的一条**：它保证**表不会悄悄落后于现实**。
# 实际项目里已经栽过两次同型（Batch 147「加了闸忘了改清单表」、
# Batch 153/154「补了索引忘了查侧栏」）——**都是新增了东西没更新汇总处**。
# 有了这一条，**下次新增闸而忘更新 A 类会被当场抓住**，而不是等下一批考古。
#
# 注入形态刻意是「**A 类多一行**」而不是「少一行」：
# 少一行在现实中不可能发生（闸不会自己消失），
# 而多一行正是「加了闸忘了登记」的真实形态。
s = sys.stdin.read()
old = "| 元数据计数 / 索引⇄标题 / 侧栏覆盖 / 内链 / 正则引擎 / 报错即失败 / 无法核对≠通过 | 闸 9 `verify-meta.py`（8 个方向） |"
assert old in s, "锚点未命中：没找到 A 类最后一行（闸 9）"
new = old + "\n| 反验注入：假装新增的第十道闸 | `scripts/verify-injected.py`（并不存在） |"
out = s.replace(old, new, 1)
assert out != s, "空转：内容未变"
assert "verify-injected.py" in out, "空转：注入特征未出现"
sys.stdout.write(out)
