#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""闸 29「同名标题」要用的归一化键（Batch 248）。

判据问的是「**目录上两个逐字相同的条目**」（Batch 245 订正后的理由），
而它原先拿**源码里的原始行**当键。真渲染器认的是**渲染后的标题文字**，
两者在六种形态上分岔。本模块把原始行折成那个文字。

**它先被量过才被用**：与 vitepress 1.6.4 渲染出的 `<h>` 文字逐条对比，
两批共 45 种形态**一致率 100%** 才进判据（实测记录在判据文件头）。
**量出来的三条修正都在下面**：
  1. **不能压内部空白**——渲染器原样保留（`多   空格` 渲染出来还是三个空格），
     压掉会把两个**显示不同**的标题判成同名。
  2. **行内代码段不许再过强调/链接替换**——渲染器把 `` ``a **b**`` `` 显示成
     `a **b**`（代码段里的星号是字面量），而顺序搞反会把它折成 `a b`。
  3. **`*` 与 `_` 的词内规则不同**（`a*b*c` 渲染成 `abc`，`_斜体_标题` 原样显示）——写成一条正则就必须迁就其中一个。
  4. **URL 里不能有空白**（`[文字](a b.md)` 不被解析成链接）。
  5. **反斜杠转义要先解**（`\*` 渲染成 `*`）。
  6. **图片在标题里不显示任何文字**（`## ![图](a.png)` 渲染出来是空的），
     所以图片替换成空串而不是 alt。
"""

import re

#: ATX 标题的**可选闭合序列**：CommonMark 允许 `## foo ##`，解析器把结尾的 `##` 丢掉。
#: 实测：真渲染器对 `## 相关页面 ##` 给出 `#相关页面`，与 `## 相关页面` **完全同名**。
_CLOSING_ATX = re.compile(r"[ \t]+#+\s*$")

#: 行内代码段（含多反引号）。**替换时整段跳过**——见文件头第 2 条。
_CODE_SPAN = re.compile(r"(`+)(.*?)\1", re.S)

#: 反斜杠转义。**转义出来的字符是字面量，不能再被后续规则当成结构**：
#: 实测 `\*星号\*` 渲染成 `*星号*`（星号原样显示），
#: 而「先解转义再跑强调」会把它折成 `星号`——**解出来的符号被吃了第二次**。
#: 所以转义字符与代码段一样**先掩码、最后还原**。
_ESCAPE = re.compile(r"\\([\\`*_{}\[\]()#+\-.!~|>])")

#: 图片 `![alt](url)` → **空**（渲染器不显示 alt）；链接 `[text](url)` → `text`。
#: **顺序要紧**：图片必须先剥，否则 `!` 会留在 text 前面。
#: **URL 里不能有空白**——实测 `链接[文字](a b.md)` **不被解析成链接**，
#: 渲染器原样显示 `链接[文字](a b.md)`，而一条 `\([^)]*\)` 会把它错认成链接。
_IMG = re.compile(r"!\[[^\]]*\]\([^)\s]*\)")
_LINK = re.compile(r"\[([^\]]*)\]\([^)\s]*\)")

#: 强调 / 强强调。**只处理行内代码之外的段。**
_STRONG = re.compile(r"(\*\*|__)(.+?)\1", re.S)
#: `*` 与 `_` 的词内规则**不同**（实测）：
#:   · `a*b*c` 渲染成 `abc` —— **`*` 允许词内**；
#:   · `_斜体_标题` 原样显示 —— **`_` 不允许词内**。
#: **写成一条正则就必须迁就其中一个，于是另一个必然错。**
_EM_STAR = re.compile(r"\*(?!\s)(.+?)(?<!\s)\*", re.S)
_EM_UNDER = re.compile(r"(?<!\w)_(?!\s)(.+?)(?<!\s)_(?!\w)", re.S)

#: 行内 HTML 标签：渲染器不显示它
_HTML = re.compile(r"</?[a-zA-Z][^>]*>")


#: 代码段的占位符。**用占位符而不是「切成段」**：实测 ``标题里有 **粗体 和 `代码`**``
#: 渲染成「标题里有 粗体 和 代码」——**` **` 横跨了代码段**，
#: 而「切成段再逐段跑正则」会让 `**` 配不上对，标题原样留下星号。
#: 占位符法让强调在**完整串**上配对，配好之后再把代码内容放回去。
_PLACEHOLDER = re.compile(r"\x00(\d+)\x00")


def _mask(text):
    """把**代码段**与**反斜杠转义出来的字符**都换成占位符。

    返回 (掩码后的串, 原文列表)。两者都必须在其它内联规则之前被保护：
    代码段里的符号是字面量，转义出来的符号**也是**字面量。
    """
    bodies = []

    def put(body):
        bodies.append(body)
        return "\x00%d\x00" % (len(bodies) - 1)

    masked = _CODE_SPAN.sub(lambda m: put(m.group(2)), text)
    masked = _ESCAPE.sub(lambda m: put(m.group(1)), masked)
    return masked, bodies


def _transform_plain(s):
    """s 已经过 `_mask`——代码段与转义字符都是占位符，不会被这里碰到。"""
    s = _IMG.sub("", s)             # ① 图片
    s = _LINK.sub(r"\1", s)        # ③ 链接
    s = _STRONG.sub(r"\2", s)      # ④ 强强调
    s = _EM_STAR.sub(r"\1", s)     # ⑤ 词内也认的星号强调
    s = _EM_UNDER.sub(r"\1", s)    # ⑥ 不认词内的下划线强调
    s = _HTML.sub("", s)
    return s


def rendered_key(raw):
    """把一行 ATX 标题的**标题文字部分**折成与渲染器一致的形态。

    `raw` 是 `## 标题文字` 这样的整行（不含行尾换行）。
    **只去掉首尾空白，不压内部空白**（见文件头第 1 条）。
    """
    m = re.match(r"^(#{1,6})([ \t]+)(.*)$", raw)
    if not m:
        return raw.strip()
    text = _CLOSING_ATX.sub("", m.group(3))
    masked, bodies = _mask(text)
    out = _transform_plain(masked)
    return _PLACEHOLDER.sub(lambda mm: bodies[int(mm.group(1))], out).strip()


def is_atx_heading(line):
    """这一行是不是 ATX 标题。

    **井号后必须是 ASCII 空格或制表符**（Batch 248 实测）：
    CommonMark 的 ATX 开头只认 U+0020 / U+0009，而 Python 的 `\s` **也匹配全角空格**。
    于是 `#　全角空格标题` 被判成 h1——**而真渲染器给的是零个标题**，
    写两个这样的行，闸 29 会报「同名标题」+「两个 H1」，
    **凭空造出两处它自己认定的缺陷，而页面上一个标题都没有。**
    """
    return bool(re.match(r"^#{1,6}[ \t]+\S", line))
