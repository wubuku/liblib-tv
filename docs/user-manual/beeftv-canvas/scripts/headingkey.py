"""闸 26 / 29 / 9 / 5 共用的标题归一化（Batch 248 建，Batch 250/251 扩）。

判据问的是「**目录上两个逐字相同的条目**」（Batch 245 订正后的理由），
而它原先拿**源码里的原始行**当键。真渲染器认的是**渲染后的标题文字**，
两者在六种形态上分岔。本模块把原始行折成那个文字。

**纪律 274 推论一：判据之间有共享概念时，那个概念只能有一份实现。**
本模块起初只有 `is_atx_heading` / `rendered_key` / `norm_inline` 三个函数
（闸 26 与闸 29 共用）。Batch 250 发现闸 9 也要全篇扫 H1，
而闸 29 早就为此写好了 `strip_fenced`——**同一件事的第二份实现**。
**两份实现只要有一份漏掉一种围栏形态，就是一个只在一半判据上生效的洞**，
所以函数搬进本模块，两处 import，行为逐字不变。
Batch 251 再把闸 5 的 `HEADING_RE` 也接了进来（它自己写了第三份）。

**Batch 251 补上了 Batch 248 没量到的那条规则：前导缩进。**
Batch 248 立了「量过一致率才进判据」的规矩，量的结论写着「两批共 45 种形态、
一致率 100%」——**那句话在它量过的形态上仍然成立**，
**但那 45 种里没有缩进标题，也没有空标题**。
Batch 251 用 vitepress 1.6.4 重跑 **30 种形态**（含前导 1/2/3 空格、
4 空格缩进、制表符缩进、空标题、井号单独一行），实测：
`is_atx_heading` 判错 **8** 种、`rendered_key` 判错 **7** 种，**全部同一个根因**——
`^(#{1,6})([ \t]+)` 这条正则**不认前导空白**，于是缩进标题走了 fallback 分支，
把整行当行内 markdown 处理，返回值里连 `##` 都留着。
**而全角空格那几种（`##　标题`）它判对了**——那正是 Batch 248 修掉的那一类，
**两条规则方向相反，所以修好一条不等于认全了另一条**（纪律 274 推论二）。
**本树 803 个标题里 0 行有前导缩进**（实测），**所以真树回归一个数都不会变**——
**这正是「现场没有」不能当护栏的又一个实例**。


**它先被量过才被用**：与 vitepress 1.6.4 渲染出的 `<h>` 文字逐条对比，
两批共 45 种形态**一致率 100%** 才进判据（实测记录在判据文件头）。
**Batch 251 订正**：那 45 种里**没有缩进标题，也没有空标题**——
本批用 vitepress 1.6.4 重跑 30 种形态（新增前导 1/2/3 空格、4 空格、制表符、
空标题、井号单独一行），实测 `is_atx_heading` 判错 8 种、`rendered_key` 判错 7 种，
**全部同一个根因**：前导空白。而**它量过的形态一个没错**——
**所以那句结论不是「错的」，是「量得不够就写成了 100%」。**
**量出来的三条修正都在下面**：
  1. **不能压内部空白**——渲染器原样保留（`多   空格` 渲染出来还是三个空格），
     压掉会把两个**显示不同**的标题判成同名。
  2. **行内代码段不许再过强调/链接替换**——渲染器把 `` ``a **b**`` `` 显示成
     `a **b**`（代码段里的星号是字面量），而顺序搞反会把它折成 `a b`。
  3. **`*` 与 `_` 的词内规则不同**（`a*b*c` 渲染成 `abc`，`_斜体_标题` 原样显示）——写成一条正则就必须迁就其中一个。
  4. **URL 里不能有空白**（`[文字](a b.md)` 不被解析成链接）。
  5. **反斜杠转义要先解**（`\*` 渲染成 `*`）。
  6. **图片在标题里不显示任何文字**（`## ![图](a.png)` 渲染出来是空的），
     所以图片替换成空串而不是 alt。
"""

import re

#: ATX 标题的**可选闭合序列**：CommonMark 允许 `## foo ##`，解析器把结尾的 `##` 丢掉。
#: 实测：真渲染器对 `## 相关页面 ##` 给出 `#相关页面`，与 `## 相关页面` **完全同名**。
_CLOSING_ATX = re.compile(r"[ \t]+#+\s*$")

#: 行内代码段（含多反引号）。**替换时整段跳过**——见文件头第 2 条。
_CODE_SPAN = re.compile(r"(`+)(.*?)\1", re.S)

#: 反斜杠转义。**转义出来的字符是字面量，不能再被后续规则当成结构**：
#: 实测 `\*星号\*` 渲染成 `*星号*`（星号原样显示），
#: 而「先解转义再跑强调」会把它折成 `星号`——**解出来的符号被吃了第二次**。
#: 所以转义字符与代码段一样**先掩码、最后还原**。
_ESCAPE = re.compile(r"\\([\\`*_{}\[\]()#+\-.!~|>])")

#: 图片 `![alt](url)` → **空**（渲染器不显示 alt）；链接 `[text](url)` → `text`。
#: **顺序要紧**：图片必须先剥，否则 `!` 会留在 text 前面。
#: **URL 里不能有空白**——实测 `链接[文字](a b.md)` **不被解析成链接**，
#: 渲染器原样显示 `链接[文字](a b.md)`，而一条 `\([^)]*\)` 会把它错认成链接。
_IMG = re.compile(r"!\[[^\]]*\]\([^)\s]*\)")
_LINK = re.compile(r"\[([^\]]*)\]\([^)\s]*\)")

#: 强调 / 强强调。**只处理行内代码之外的段。**
_STRONG = re.compile(r"(\*\*|__)(.+?)\1", re.S)
#: `*` 与 `_` 的词内规则**不同**（实测）：
#:   · `a*b*c` 渲染成 `abc` —— **`*` 允许词内**；
#:   · `_斜体_标题` 原样显示 —— **`_` 不允许词内**。
#: **写成一条正则就必须迁就其中一个，于是另一个必然错。**
_EM_STAR = re.compile(r"\*(?!\s)(.+?)(?<!\s)\*", re.S)
_EM_UNDER = re.compile(r"(?<!\w)_(?!\s)(.+?)(?<!\s)_(?!\w)", re.S)

#: 行内 HTML 标签：渲染器不显示它
_HTML = re.compile(r"</?[a-zA-Z][^>]*>")


#: 代码段的占位符。**用占位符而不是「切成段」**：实测 ``标题里有 **粗体 和 `代码`**``
#: 渲染成「标题里有 粗体 和 代码」——**` **` 横跨了代码段**，
#: 而「切成段再逐段跑正则」会让 `**` 配不上对，标题原样留下星号。
#: 占位符法让强调在**完整串**上配对，配好之后再把代码内容放回去。
_PLACEHOLDER = re.compile(r"\x00(\d+)\x00")


def _mask(text):
    """把**代码段**与**反斜杠转义出来的字符**都换成占位符。

    返回 (掩码后的串, 原文列表)。两者都必须在其它内联规则之前被保护：
    代码段里的符号是字面量，转义出来的符号**也是**字面量。
    """
    bodies = []

    def put(body):
        bodies.append(body)
        return "\x00%d\x00" % (len(bodies) - 1)

    masked = _CODE_SPAN.sub(lambda m: put(m.group(2)), text)
    masked = _ESCAPE.sub(lambda m: put(m.group(1)), masked)
    return masked, bodies


def _transform_plain(s):
    """s 已经过 `_mask`——代码段与转义字符都是占位符，不会被这里碰到。"""
    s = _IMG.sub("", s)             # ① 图片
    s = _LINK.sub(r"\1", s)        # ③ 链接
    s = _STRONG.sub(r"\2", s)      # ④ 强强调
    s = _EM_STAR.sub(r"\1", s)     # ⑤ 词内也认的星号强调
    s = _EM_UNDER.sub(r"\1", s)    # ⑥ 不认词内的下划线强调
    s = _HTML.sub("", s)
    return s


def norm_inline(text):
    """把一段**行内 markdown**（没有 ATX 前缀）折成读者看到的那串文字。

    `rendered_key` 与**链接文字**都必须走它——
    **两边走同一套规则才叫比较**：链接文字同样会被渲染，
    而读者是把「链接显示的那几个字」拿去和「标题显示的那几个字」比的。
    闸 19（`verify-link-labels.py`）原先拿**链接原始文本**比**标题原始文本**，
    那个方向在**两边都带反引号**时恰好成立（实测本树的
    `[新建创作（\`/create\`）]` 与 `## 新建创作（\`/create\`）` 就是这样），
    **但只要有一边带 ATX 闭合井号、或者一边是全角空格那种伪标题，就分岔**。
    """
    t = _CLOSING_ATX.sub("", text)
    masked, bodies = _mask(t)
    out = _transform_plain(masked)
    return _PLACEHOLDER.sub(lambda mm: bodies[int(mm.group(1))], out).strip()


def rendered_key(raw):
    """把一行 ATX 标题的**标题文字部分**折成与渲染器一致的形态。

    `raw` 是 `## 标题文字` 这样的整行（不含行尾换行）。
    **只去掉首尾空白，不压内部空白**（见文件头第 1 条）。

    **Batch 251**：前导缩进与空标题这两种形态旧版都判错
    （` ## 标题` 返回 `'## 标题'`、`#` 返回 `'#'`）——
    根因是 `^(#{1,6})([ \\t]+)` 不认前导空白，于是整行走 `norm_inline` fallback，
    **返回值里连井号都留着**。现在直接取 `atx_level` 认出来的级别，
    **井号之后剩下的全部内容**交给 `norm_inline`（闭合序列、行内代码、
    强调、链接、图片、反斜杠转义都由它处理，已与渲染器逐条对齐）。
    """
    lv = atx_level(raw)
    if lv is None:
        return norm_inline(raw)
    m = re.match(r"^ {0,3}#{1,6}", raw)
    return norm_inline(raw[m.end():])



def atx_level(line):
    """这一行是几级 ATX 标题，不是标题就返回 `None`。

    **这是「什么算标题」在本模块里的唯一一份实现**
    （`is_atx_heading` / `rendered_key` / `first_h1` 都走它）。

    规则照 CommonMark 的 ATX 开头，**Batch 251 用 vitepress 1.6.4 逐条量过**
    （30 种形态，见文件头）：

      · **前导 0-3 个 ASCII 空格合法，4 个就不是标题了**——
        实测 ` ## 标题` / `  ## 标题` / `   ## 标题` 渲染成 `<h2>`，
        而 `    ## 标题`（4 空格）与 `\\t## 标题`（制表符）**渲染成代码块**。
        **制表符不算缩进**：CommonMark 把 4 空格与 1 制表符同等看待，
        所以 1 个制表符就已经越界。
      · **井号后必须接空白或直接到行尾**——
        `##标题` 不是标题（实测渲染成普通段落），
        而 `## `（只有空白）与 `#`（井号单独一行）**都是标题**（`<h2>` / `<h1>`，文字为空）。
        Batch 248 的旧式 `#{1,6}[ \t]+\\S` 要求井号后有空白**且有非空白字符**，
        **于是把空标题也判没了**。
      · **1-6 个井号**：`####### 标题`（7 个）不是标题。
      · **空白只能是 ASCII 空格与制表符**——`##　标题`（全角空格）不是标题，
        而 Python 的 `\\s` **会匹配全角空格**（Batch 248 踩过）。
    """
    m = re.match(r"^ {0,3}(#{1,6})(?:[ \t]|$)", line)
    return len(m.group(1)) if m else None


def is_atx_heading(line):
    """这一行是不是 ATX 标题。**实现见 `atx_level`**（Batch 251 起只此一份）。

    **井号后必须是 ASCII 空格或制表符**（Batch 248 实测）：
    CommonMark 的 ATX 开头只认 U+0020 / U+0009，而 Python 的 `\\s` **也匹配全角空格**。
    于是 `#　全角空格标题` 被判成 h1——**而真渲染器给的是零个标题**，
    写两个这样的行，闸 29 会报「同名标题」+「两个 H1」，
    **凭空造出两处它自己认定的缺陷，而页面上一个标题都没有。**
    """
    return atx_level(line) is not None



def strip_fenced(text):
    """挖空围栏代码块但**保留行数**——报错要带 `:行号`，行号必须对得上原文。

    **Batch 250 从 `verify-heading-uniqueness.py` 原样搬来**（纪律 274 推论一：
    判据之间有共享概念时，那个概念只能有一份实现）。
    闸 29 的判据 1「排除围栏代码块」靠它，闸 9 的 H1 提取靠它。

    **为什么必须剥**：任务页里全是 bash 代码块，而 `# 注释` 是 bash 的常规写法。
    全篇扫 H1 而不剥围栏，**第一行 `# 这是注释` 就会被当成页面 H1**——
    于是页面标题变成一句代码注释，索引对账拿着它去比，**报出来的诊断是错的**。
    **本树任务页围栏内当前 0 处形似标题的行**（实测），
    **而这恰恰说明它不能靠现场数据兜住**——只有真出现时才炸的洞，
    要靠用例钉，不能靠「反正现在没有」。

    围栏行本身（``` 开闭那几行）也换成空串：**闭合围栏的那一行如果写成
    ` ```bash ` 之外还带井号，它同样不该进标题集合**。
    """
    out, in_fence, fence = [], False, None
    for line in text.split("\n"):
        m = re.match(r"^[ \t]*(```|~~~)", line)
        if m:
            if not in_fence:
                in_fence, fence = True, m.group(1)
            elif m.group(1) == fence:
                in_fence, fence = False, None
            out.append("")
            continue
        out.append("" if in_fence else line)
    return "\n".join(out)


def first_h1(text):
    """返回页面里**第一个 H1 标题的原始整行**，没有就返回 `None`。

    **为什么是「全篇扫」而不是「读首行」**（Batch 250 实测）：
    旧判据 `open(path).readline()` 之后判 `startswith("# ")`，
    **首行不是 H1 时它不是「报错」，是「这一页从此不再被检查」**——
    实测把 `asset-library.md` 首行清空（真 H1 移到第 2 行），
    闸 9 报 rc=0，还打印「✓ 任务索引双向一致：**28 个任务页全部登记**」
    （真树 29），而那 29 条链接里有 1 条**根本没被比过**。
    **一个判据的默认分支是「不看」，漏报就是它的静默形态。**

    同一个 `readline()` 假设在 `sidebar_check()` 里被复制了第二份，
    所以**同一个洞让两个方向一起缩了**（侧栏那条也打印「28 个任务页全部在侧栏」）。
    本函数是唯一的一份。

    **只取第一个 H1**：vitepress 认页面标题也只看第一个，
    多 H1 是闸 29 判据 4 的职责（`全文有且只有一个 H1`）——**分工写在这里，
    不留在代码里当免责**。

    **Batch 251**：级别改由 `atx_level()` 给（原先是 `^#[ \\t]+\\S`，
    **既不认前导缩进也不认空标题**，而 ` ## 标题` 与 `#` 渲染器都认）。
    """
    for line in strip_fenced(text).split("\n"):
        if atx_level(line) == 1:
            return line
    return None

