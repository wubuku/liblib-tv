"""「空手册树」这件事的**单一来源**（Batch 279 新建）。

**为什么要有这个模块**：闸 41 `verify-empty-tree.py` 与
`selftest-zero-input.py` 的方向一/二**要问同一个问题**——
「在一棵什么都没有的手册树上，每道闸会说什么」——
**而它们的判据必须逐字同一套**，否则「一处报了另一处没报」无法解释成「它们看的不是同一件事」。

**收敛前量过等价**（纪律 250 / 纪律 296）：
  · `ZERO_COUNT_RE` —— 闸 37 判据重复实测抓到它**逐字出现在两个文件里**，
    登记表里没有它。**这是纪律 274 说的那个形态**（「共享概念只能有一份实现」），
    **而两处都工作正常，所以没有任何行为会报这件事**——**判据重复就是为它存在的**；
  · `EXEMPT` —— 三道闸的输入不在手册树内，空树上它们报红是**对的**；
  · `empty_tree()` —— 建树的那几行。

**切面只取「两边真正一样的那部分」**（纪律 296）：
  · **`run_gates()` 没有收进来**，因为两边问的**不是同一件事**——
    闸 41 抓「报绿」与「崩溃」并**把超时单列**；
    `selftest-zero-input.py` 的方向三还要抓「走了兜底却一声不吭」与「说了落点但落点站不住」
    （方向三之三 / 方向三之四），**那两个形态只在那一次运行里才存在**。
    **把它们并进同一个函数就是一次没人申请的语义变更。**
  · **本模块不含任何 `.md` 路径假设**，所以它对两边的用法是对称的。
"""
import os
import re

#: 「0 个 X」形态。**只认 0**，因为「N 个文件全部合格」是正常输出。
#: **这个正则是纪律 156 的机械化**：判据必须报出「它实际核了几项」，
#: 而「一个都没检查」与「全部都合格」在退出码上一样、在措辞上也几乎一样。
ZERO_COUNT_RE = re.compile(r"(\d+)\s*个(?:文件|页面|张|项|条|篇|断言|任务|反验|目录)")

#: 输入不在手册树内、因此在空树上报红是**对的**的那几道。
#: **调用方要自己把「自己」并进豁免**——本模块不该知道谁在用它
#: （闸 41 在空树上会跑「全部闸」，**不排除自己就是无限递归**）。
EXEMPT = {
    "verify-selftest-deps.py",      # 核的是 scripts/ 里的反验，与手册文件无关
    "verify-selftest-bootable.py",  # 同上
    "verify-encoding.py",           # 白名单里的 .py 仍在树内，它确实核了东西
}


def empty_tree(tmp, stage):
    """一棵空手册树：只有闸脚本与共用模块，**没有任何 .md / 截图 / 清单**。

    **`stage` 由调用方传进来**（`stagedeps.stage_all`），
    **而本模块不 import 它**——理由与闸 18 的「重复而不共用是有意的」相反：
    **这里共用是对的，因为两个调用方要的就是同一份搬运行为**，
    **而 `stage_all` 已经在 `stagedeps` 里是单一来源**（Batch 253 收敛过一次）。

    `verify=False` 的理由：空树上的闸在启动阶段抛错是**正常结局之一**
    （那正是要抓的东西），**真去 import 一次会在搬运阶段就炸**，
    **于是整道闸连跑都跑不起来**。
    """
    os.makedirs(os.path.join(tmp, "scripts"), exist_ok=True)
    os.makedirs(os.path.join(tmp, ".vitepress"), exist_ok=True)
    stage(tmp, verify=False)
    return tmp
