import sys
# 用例 45（不误伤方向）：H1 写成 CommonMark 的**ATX 闭合序列**形态，索引写渲染后的名字。
#
# `# 素材库（资产页） ##` 渲染出来就是「素材库（资产页）」——
# 真渲染器把那串 ` ##` 丢掉（与 vitepress 1.6.4 量过，见 headingkey.py 文件头；
# **Batch 251 补测到 65 种形态**——Batch 248 那 45 种里没有缩进标题与空标题）。
# 索引里写的是读者在页面上真正看到的那串字，**所以必须放行**。
#
# 实测（Batch 250，判据改前 vs 改后，同一个注入）：
#   改前 rc=1  ✗ 索引里 asset-library.md 的链接文字「素材库（资产页）」与页面标题「素材库（资产页） ##」既不相同
#   改后 rc=0  ✓ 任务索引双向一致：29 个任务页全部登记
#
# **改前那条诊断引用的「素材库（资产页） ##」这串字，页面上根本不存在。**
# 这不是「严格了一点」，是**判据在拿读者看不见的东西当标题报出去**——
# 而按它去改的人，会把好端端的索引链接改成 `素材库（资产页） ##`（Batch 246 闸 8 的同款：
# 照着假诊断改，会把好表改坏）。
#
# 这条是闸 26 `verify-link-labels.py` 在 Batch 249 修过的同一个口径问题，
# 本批把它接到闸 9 上——**纪律 274 推论一：共享概念只能有一份实现**。
s = sys.stdin.read()
anchor = "# 素材库（资产页）\n"
assert anchor in s, "锚点未命中：asset-library.md 首行不是预期的 H1"
s = s.replace(anchor, "# 素材库（资产页） ##\n", 1)
assert s != anchor, "注入空转"
sys.stdout.write(s)
