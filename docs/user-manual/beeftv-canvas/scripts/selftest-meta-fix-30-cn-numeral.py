import sys
# 把标题改成「十一道闸」——`_cn_int` 若只认单个汉字就会解析成 None，
# 方向三会报「找不到「现有 N 道闸」标题」。
# **真实仓库的标题是「十道闸」（单字），覆盖不到这条路径**，所以必须专门钉一条。
s = sys.stdin.read()
anchor = "### 现有十道闸"
assert anchor in s, "锚点未命中：找不到「### 现有十道闸」"
s = s.replace(anchor, "### 现有十一道闸", 1)
# 表只有 10 行，所以方向三应报「标题写 11 道闸、清单表却有 10 行」——
# **这正是我们要的证据：它证明了标题被成功解析成了 11，而不是 None。**
sys.stdout.write(s)
