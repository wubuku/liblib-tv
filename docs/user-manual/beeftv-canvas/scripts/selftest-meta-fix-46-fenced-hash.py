import sys
# 用例 46（不误伤方向，**钉的是新判据自己新引入的风险**）：
# 在 H1 之前放一个含 `# 这是注释，不是标题` 的 bash 围栏块。
#
# 前 45 条用例里没有一条会伤到它，因为旧判据只读首行、看不见页面中段。
# **而本批新判据改成全篇扫 H1，于是「代码块里的井号被当成页面标题」成了一个新洞。**
# 任务页里全是 bash 代码块，而 `# 注释` 是 bash 的常规写法——
# 真出现时，页面标题会变成一句代码注释，索引对账拿着它去比，
# 报出来的是「页面标题『这是注释，不是标题』与链接文字不一致」：**诊断是编的**。
#
# **本树任务页围栏内当前 0 处形似标题的行（实测）**，所以真树回归跑不出这个洞。
# 「现场没有」不能当护栏——**只有真出现时才炸的洞，要靠用例钉**。
# 反事实实测（Batch 250）：把 `first_h1` 里的 `strip_fenced` 去掉、其余不动，
# 同一个注入上 rc=1 且报出上面那句编造的诊断。**这就是本用例的鉴别力。**
s = sys.stdin.read()
anchor = "# 素材库（资产页）\n"
assert s.startswith(anchor), "锚点未命中：asset-library.md 首行不是预期的 H1"
fence = "```bash\n# 这是注释，不是标题\nnpm run build\n```\n\n"
s = fence + s
assert s != anchor, "注入空转"
sys.stdout.write(s)
