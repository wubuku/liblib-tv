import sys
# 用例 47（不误伤方向）：任务页的 H1 **写成缩进形态**（` # 素材库（资产页）`）。
#
# **Batch 251 实测**：vitepress 1.6.4 把前导 1-3 个 ASCII 空格的 ATX 开头
# 渲染成标题（4 空格与制表符则渲染成**代码块**），
# 而 Batch 250 刚加的 `headingkey.first_h1()` 当时是 `^#[ \t]+\S`——
# **既不认前导缩进也不认空标题**，于是这一页被判成「全文没有任何 H1」。
#
# 方向是**误报**：页面上确实有一个 H1，渲染出来也确实有，
# 而判据报「全文没有任何 H1」并把它归进 Batch 250 刚钉的那条「不得静默」的必报项——
# **把一条刚写好的守卫，变成了一个会让人去改手册的假警报**。
# 改前实测 rc=1（误报），改后 rc=0。
#
# **与用例 46 的分工**：46 钉「新判据不该把代码围栏当标题」，
# 本条钉「新判据该认的形态一个都不能漏」——
# **一条钉「多认」，一条钉「漏认」，只写一条就只守住半个方向。**
#
# ── 本文件第一版写错了，而且错法值得记下来（Batch 251）─────────────────
# 第一版把它写成「直接打开 ROOT 下的文件改掉」（像用例 44 那样），
# 然后交给 `run_file_pass_case` 跑——**而那个 helper 要求 fixer 是
# 「从 stdin 读、把结果写 stdout」的过滤器**。于是：
#   脚本自己改了真文件 → `mv "$target.injected" "$target"` 又把**空输出**盖了回去
#   → 判据看到的不是「缩进 H1」，而是一个**被清空的页面**，
#   → 它报「全文没有任何 H1」，用例判失败。
# **故障现象与「判据不认缩进」一模一样，而真因在反验这一侧。**
# 这正是本脚本头写着的那条纪律的一个新实例：
# **「注入失败 = 没注入 = 基线状态 = 放行 = 通过」属于假通过**，
# 而 `run_file_pass_case` 走 stdin/stdout 通道时，
# **「脚本没走那条通道」既不产生错误也不改变退出码**。
# 改成与 43/45/46 同一个形态（stdin → stdout）后，
# `run_file_pass_case` 既有 `cmp -s` 空转检查、也保证只改 `$target` 一个文件。
s = sys.stdin.read()
h1 = "# 素材库（资产页）\n"
assert s.startswith(h1), "锚点未命中：asset-library.md 首行不是预期的 H1"
s = " # 素材库（资产页）\n" + s[len(h1):]
assert s != h1, "注入空转"
sys.stdout.write(s)
