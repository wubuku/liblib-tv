# -*- coding: utf-8 -*-
"""把截图清单切成一组块——**两个截图闸共用的一份实现**（Batch 264）。

**它收的是闸 37 登记表里最后那一条重复**（`0ffab7a538d5`）：
`verify-shot-integrity.py` 与 `verify-shot-version-source.py`
各写了一份**逐字相同**的
`REC_RE = re.compile(r"^  - file:\s*(\S+)\n(.*?)(?=^  - file:|\Z)", re.S | re.M)`，
而它们各自的 `parse_manifest()` **开头三行也逐字相同**（读文本 → 遍历 → 取 `group(1)`/`group(2)`）。

**⚠️ 本批订正了那条登记理由——它当时写的是错的。**
原文：「**而它们的输入格式本身是各自闸的输出**——
**收敛的前提是先统一那两个闸的输出格式**，那比收敛一条正则大得多。」

**实测它们读的是同一个文件**：`screenshots/manifest.yml`——
**两处 `MANIFEST` 常量的值都是 `os.path.join(ROOT, "screenshots", "manifest.yml")`**，
**而那份文件是手册自己的截图登记册（67 条 `- file:` 记录），不是任何一个闸的输出。**
**所以「先统一输出格式」这个前提根本不存在**——
**登记表里那句「理由」本身是一句不可核实的断言**（纪律 295 推论二），
**而这一批就是把它证伪的那一批**。
**推论**：**一条登记的「为什么没收敛」比「为什么重复」更容易过期**——
**因为它描述的是当时的判断，而判断的依据会被人改掉，理由却留在原地。**

**收敛的切面仍然是「切块」，不是「读文件」**（纪律 296）：
两个闸**读同一个文件，但失败策略不同**——
`verify-shot-integrity.py` 直接 `open()`（读不到就抛），
`verify-shot-version-source.py` 用 `try/except OSError` **读不到就返回 None 并打「未能核对」**。
**那是有意的差别**（纪律 101：事实源读不到必须 rc=2，不能安静地全绿），
**所以入参是「已经读好的文本」，读与失败都留在各自那一侧。**

零外部依赖，与 `beefsrc` / `batchread` / `selftestnames` / `tablerow` 一致。
"""

import re

#: **一条记录 = 一个 `- file:` 块**，块体一直取到下一个 `- file:` 或文本末尾。
#: **`re.S` 让 `.` 跨行**（块体是多行的），**`re.M` 让 `^`/`$` 认行首行尾**。
#: **两条 flag 少任何一条都不对**：`re.M` 没了则块体只到第一行，
#: `re.S` 没了则 `.*?` 根本跨不过行。
REC_RE = re.compile(r"^  - file:\s*(\S+)\n(.*?)(?=^  - file:|\Z)", re.S | re.M)


def blocks(text):
    """把清单文本切成 `[(文件名, 块体文本), …]`。

    **入参是「已经读好的文本」而不是路径**：两个闸读同一份文件，
    **但一个读不到就抛、一个读不到就 `None`**——
    **把那件事一起收进来就等于抹掉一个有意的差别**（纪律 296 推论一）。
    """
    return [(m.group(1), m.group(2)) for m in REC_RE.finditer(text)]
