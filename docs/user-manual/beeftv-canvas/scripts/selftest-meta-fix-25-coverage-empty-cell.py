import sys
# 方向九反验用例 25：把覆盖度表里 C 类的一行**依据列清空** → 期望方向九报出。
#
# 这条守的是 Batch 161 的核心主张：**「空格看起来像有人管，其实没有」**。
# Batch 161 的教训是**连着好几批都有人以为某类问题有人管**（侧栏 20 批、
# 内链、fails += 1 两次、11 处 skip）——共同形态就是**表里/说明里留了一个空位，
# 而空位不会被任何机制追问**。
#
# 注入点选 C 类里一条**确实无人覆盖**的风险类别，把它写成「待定」——
# **这正是现实中会发生的形态**：有人加了一行，但没想清楚谁管。
s = sys.stdin.read()
old = "| 运行时行为（按钮是否真的不渲染） | 闸 7 只看源码判据，无法验证运行时；截图是唯一的运行时证据，又受上一行所限 |"
assert old in s, "锚点未命中：没找到 C 类「运行时行为」那一行"
new = "| 运行时行为（按钮是否真的不渲染） |  |"
out = s.replace(old, new, 1)
assert out != s, "空转：内容未变"
assert "| 运行时行为（按钮是否真的不渲染） |  |" in out, "空转：注入特征未出现"
sys.stdout.write(out)
