# -*- coding: utf-8 -*-
"""注入：改写 `timeline-editing.md` 里被引用的那句「运行时实证」的措辞。

验的是方向六之二（页内相对指代不许悬空）**抓不抓得住**。

被测的那句话是 Batch 221 写的证据分层声明：
「**上面那句**「运行时实证」说的是弹窗结构 / 自动铺轨 / 片段选中编辑…
**而本节的**轨道默认值…只做了源码核对」。

它靠「上面那句」定位。**把上面那句里的「运行时实证」改掉，下面这句就悬空了**——
而悬空的分层声明**比没有更坏**：读者被告知证据等级不同，
却找不到该去比对的另一处，**于是只能假设两层一样**。

**这正是这个方向存在的理由**：耦合是隐式的，
今天全对，可没有任何东西在盯它下一次还对不对。
"""
import sys

# **锚点刻意不含版本号**（首版写的是「运行时实证：多轨时间线弹窗已真实走查」，
# 而真实原文是「运行时实证（v1.6.14 构建实测）：…」——**版本号一升锚点就失配**，
# 而锚点失配的用例会被作废，于是这条鉴别力**静默消失**。
# 「> 运行时实证（」带行首标记和全角左括号，L42 那句「上面那句「运行时实证」说的是」
# 不含这个形态，所以唯一。
OLD = "> 运行时实证（"
NEW = "> 实际走查（"

s = sys.stdin.read()
assert s.count(OLD) == 1, "锚点「运行时实证：多轨时间线弹窗已真实走查」不唯一（%d 处）——空转，作废本用例" % s.count(OLD)
out = s.replace(OLD, NEW, 1)
assert out != s, "替换后内容没变——空转，作废本用例"
sys.stdout.write(out)
