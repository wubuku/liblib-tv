"""注入：把「上面那句「运行时实证」」改写成自指形态「本节提到的「运行时实证」」。

**与用例 40 成对**：同一个文件、同一句话、同一处耦合，**只因指代方式不同，结论就该相反**。

用例 40 钉的是「能抓」——指代被改写导致悬空必须报。
**这一条钉的是「不误伤」**：「本节」指的是**本小节自己**，它在这张手册里**恒成立**，
所以方向六之二**刻意不查它**（查了就是稳定误报，而误报会逼着人加豁免，越修越乱）。

**没有这一对，用例 40 可能只是「逢『运行时实证』就报」**——
那种判据一样绿，但它会把作者正常写下的「本节」全部报成问题。
"""
import sys

OLD = "上面那句「运行时实证」说的是"
NEW = "本节提到的「运行时实证」指的是"

s = sys.stdin.read()
assert s.count(OLD) == 1, "锚点「上面那句「运行时实证」说的是」不唯一（%d 处）——空转，作废本用例" % s.count(OLD)
out = s.replace(OLD, NEW, 1)
assert out != s, "替换后内容没变——空转，作废本用例"
sys.stdout.write(out)
