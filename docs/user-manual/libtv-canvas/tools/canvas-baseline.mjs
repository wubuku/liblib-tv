//       React 的批量更新会把位移整个吞掉 —— ±1px 到 ±30px 位移**全是 0**。
//    ② **落点会被吸附到 12 画布单位的格点**，且**每轮必须重找落点**
//       （节点一动，原落点就落到框外，FB-11 的往返因此净位移 48）。
//       ⇒ 复原必须写成「拖 → 读回 → 算差 → 再拖」的闭环，绝不能一次到位。
//    ⭐⭐ 补充（FD）：**`⌘0`（fit view）之后 zoom 不是常驻值** —— 节点群包围盒变了，
//       fit 出来的 zoom 也会变。凡是用 zoom 换算像素的脚本，每轮都要**重新读**。
//    ⭐⭐ 补充（FD）：**框选状态下 `querySelectorAll('.react-flow__node')` 会漏读**
//       （FD-4 只读到 4 个 / 11 个），必须逐个用
//       `document.querySelector('.react-flow__node[data-id="…"]')` 读。
