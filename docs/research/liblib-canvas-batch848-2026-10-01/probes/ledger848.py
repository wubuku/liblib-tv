def main() -> int:
    row = ROW
    # ── 自校验 ①：行首 ──
    if not row.startswith("| Batch 848 |"):
        print("✘ 行首不是 `| Batch 848 |`")
        return 1
    # ── 自校验 ②：竖线**恰好 4** ──
    n_pipe = row.count("|")
    if n_pipe != 4:
        print("✘ 竖线总数 %d（应为 4）⟹ 正文里有裸竖线" % n_pipe)
        return 1
    # ── 自校验 ③：**0 个 U+FFFD** ──
    n_bad = row.count("\ufffd")   # ★ 用转义写 ⟹ ⟹ 免得 macOS 的终端/编辑器把字符本身吃掉
    if n_bad != 0:
        print("✘ 新行有 %d 个 U+FFFD" % n_bad)
        return 1
    # ── 自校验 ④：**只追加**，不重写历史行 ──
    if LEDGER.exists():
        old = LEDGER.read_text(encoding="utf-8")
        if "| Batch 848 |" in old:
            print("✘ 台账里已经有 Batch 848 了 ⟹ 不重复追加")
            return 1
        if not old.endswith("\n"):
            old += "\n"
        LEDGER.write_text(old + row + "\n", encoding="utf-8")
    else:
        LEDGER.write_text(row + "\n", encoding="utf-8")
    print("✔ 已追加到", LEDGER)
    print("  竖线 %d 个 ✔ ／ U+FFFD %d 个 ✔" % (n_pipe, n_bad))
    return 0


if __name__ == "__main__":
    sys.exit(main())
