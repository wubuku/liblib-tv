def main() -> int:
    problems = []
    for rel, pairs in EDITS:
        path = ROOT / rel
        text = path.read_text(encoding="utf-8")
        for old, new in pairs:
            n = text.count(old)
            if n == 0:
                # ★ 可能是「上一条替换已把它改掉」（⟹ ⟹ 幂等）⟹ ⟹ 跳过但要报出来
                problems.append("未命中：%s ⟹ %r" % (rel, old[:60]))
                continue
            if n > 1:
                problems.append("命中 %d 次（不唯一）：%s ⟹ %r" % (n, rel, old[:60]))
                continue
            text = text.replace(old, new, 1)
        path.write_text(text, encoding="utf-8")
        print("已改：", rel)
    if problems:
        print("\n★ 有未命中/不唯一的替换：")
        for p in problems:
            print("   ", p)
        return 1
    print("\n全部替换唯一命中 ✓")
    return 0


if __name__ == "__main__":
    sys.exit(main())
