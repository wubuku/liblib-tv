def main():
    row = ROW
    problems = []
    if not row.startswith("| Batch 845 |"):
        problems.append("行首不是 `| Batch 845 |`")
    pipes = row.count("|") - row.count("\\|")
    if pipes != 4:
        problems.append("竖线数 = %d（期望 4）" % pipes)
    if row.count("\ufffd"):
        problems.append("含 %d 个 U+FFFD" % row.count("\ufffd"))
    if "REGRESSION_PLACEHOLDER" in row:
        problems.append("回归段还是占位符 ⟹ 先填回归结果")
    if problems:
        print("★ 不合格，不写入：")
        for p in problems:
            print("   ", p)
        return 1
    text = LEDGER.read_text(encoding="utf-8")
    if "| Batch 845 |" in text:
        print("★ 台账里已经有 Batch 845 的行了 ⟹ 不重复追加")
        return 1
    with LEDGER.open("a", encoding="utf-8") as fh:
        fh.write(row + "\n")
    print("已追加：", LEDGER)
    print("行长度：", len(row), "｜ 竖线：", pipes, "｜ U+FFFD：", row.count("\ufffd"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
