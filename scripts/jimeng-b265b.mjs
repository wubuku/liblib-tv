// ---------- 词表 v2：每一档都写清为什么在这一档 ----------
// 强标记：出现即**几乎必然**是订正（订正动作本身或推翻的明示）
const 强标记 = [
  '订正', '推翻', '已被批次', '不成立', '作废', '未复现', '已删除', '已过时', '已关闭', '~~',
  '🔧',            // 缺陷②：旧记订正专用记号，b265 漏了
  '是错的',        // 缺陷②：字面纠错
  '已经过期',      // 缺陷②：字面纠错
];
// 弱标记：`🔴`/`⚠️`/`❌` 单独出现只是警告，**不能**算订正（b265 的教训）
const 弱标记 = ['🔴', '⚠️', '❌'];
// 引述标记：在**复述**一条历史说法（多半已被推翻），附近无标记属正常（缺陷③）
const 引述标记 = [
  '原话', '记下', '记了', '记的', '原写', '此前', '旧记', '历史记录', '旧记录',
  '原来说', '早已', '先前', '转述', '本批之前',
];

const 判标记 = (文本) => ({
  强: 强标记.filter((w) => 文本.includes(w)),
  弱: 弱标记.filter((w) => 文本.includes(w)),
  引述: 引述标记.filter((w) => 文本.includes(w)),
});

const 内容页前缀 = ['10-tasks/', '20-reference.md', '30-concepts.md', '90-troubleshooting.md', '00-quickstart.md'];
const 日志页名 = ['AUDIT.md', 'PROGRESS.md', 'SOURCE_OBSERVATIONS.md'];
const 归类 = (f) => (内容页前缀.includes(f) || 内容页前缀.some((p) => f.startsWith(p)) ? '内容页'
  : 日志页名.includes(f) ? '日志页' : '其它');

const 走 = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
  const p = path.join(dir, d.name);
  if (d.isDirectory()) return d.name === 'node_modules' ? [] : 走(p);
  return d.name.endsWith('.md') ? [p] : [];
});
const 文件 = 走(手册根).map((f) => ({ 名: path.relative(手册根, f), 行: fs.readFileSync(f, 'utf8').split('\n') }));

const 是表格行 = (行) => { const t = 行.trim(); return t.startsWith('|') && t.endsWith('|') && t.length > 1; };
const 是分隔行 = (行) => /^\s*\|?[\s:\-|]+\|[\s:\-|]*$/.test(行) && 行.includes('|') && 行.includes('-');
const 是标题 = (行) => /^#{1,6}\s/.test(行);
const 是围栏 = (行) => /^\s*```/.test(行);

/** 缺陷①的修法：按**分节**切邻域 —— 空行 / 标题 / 表格分隔 / 代码围栏 都是节界 */
const 分节 = (行, i) => {
  const is界 = (l) => l.trim() === '' || 是标题(l) || 是分隔行(l) || 是围栏(l);
  let a = i, b = i;
  while (a > 0 && !is界(行[a - 1])) a--;
  while (b < 行.length - 1 && !is界(行[b + 1])) b++;
  return { 起: a, 止: b };
};

/**
 * 📌 阴性对照用例 ② 逼出来的**第二处**修法（分节本身还不够）：
 *   真实文件里订正写成 `#### 🔴 订正批次 178：…不成立`，**标题**在 3 行之上
 *   且**被空行隔开** —— 分节在空行处断开，标题落在节外。
 *   🔴 根因：**空行分隔的是排版内容，不是语义单元**；
 *     `####` 标题是这个块**整体**的判定门面。
 *   ⇒ 邻域必须**额外并入最近的上级标题行**。
 */
const 并标题 = (行, i) => {
  for (let k = i; k >= 0; k--) if (是标题(行[k])) return k;
  return -1;
};
const 邻域行 = (行, i) => {
  // 📌 阴性对照用例 ⑦ 逼出来的**第三处**修法：命中行**本身是标题**时，
  //   排版分节只剩标题这一行，看不到标题**下面的正文** ——
  //   而订正恰恰常写在标题下的第一段（`90-troubleshooting.md:1065` 就是这样）。
  //   ⇒ 标题行的窗口 = 它的**语义块**（标题 + 正文，直到下一个同级或更高级标题）。
  const 节 = 是标题(行[i]) ? 语义块(行, i) : 分节(行, i);
  const 标 = 并标题(行, i);
  const 段 = 行.slice(节.起, 节.止 + 1);
  if (标 >= 0 && 标 < 节.起) 段.unshift(`⟪标题⟫${行[标]}`);
  return 段;
};

/**
 * 📌 真实文件上又暴露的**第三处**修法（`并标题` 仍不够，两个方向都漏）：
 *   `subject-node.md:132` 的订正在**上两行**的正文里（`:130` 有 `~~`+`订正`，
 *     中间隔一个空行 ⇒ 严格窗口看不到）；`90-troubleshooting.md:1065` 命中的
 *     是 `###` **标题行本身**，订正在它**下面两行**的正文里 ⇒ 也看不到。
 *   🔴 同一个洞的两面：**订正标记住在「Markdown 章节块」里，而窗口是「排版分节」。**
 *
 * 📌 因此改成**双窗口**，两个都读、都量、都交出去：
 *   A 严格 = 排版分节 ∪ 最近上级标题 ⇒ **用来判档**（细、准、噪声大）
 *   B 宽松 = 语义块（最近的同级或更高级标题起，到下一个同级或更高级标题止）
 *           ⇒ **只用来交叉验证**：若某条在 B 下**仍无**强标记，
 *             它才是真正需要人眼看的一类。
 *   🔴 两窗口**方向相反**，所以缺口的**真值落在 A 的残差上**（人眼判读），
 *     而 B 的作用是证明「连最宽松的章节口径也没有一条在裸奔」。
 */
const 标题级 = (l) => { const m = l.match(/^(#{1,6})\s/); return m ? m[1].length : 0; };
const 语义块 = (行, i) => {
  const h = 并标题(行, i);
  if (h < 0) return 分节(行, i);
  const L = 标题级(行[h]);
  let e = h;
  for (let k = h + 1; k < 行.length; k++) {
    const lv = 标题级(行[k]);
    if (lv && lv <= L) break;
    e = k;
  }
  return { 起: h, 止: e };
};

/** 缺陷③的修法：最近的上级标题是否属于「立规 N」方法论小节 */
const 立规节 = (行) => {
  let 最近 = '';
  for (let i = 0; i < 行.length; i++) if (是标题(行[i])) 最近 = 行[i];
  return /立规\s*\d+/.test(最近) ? 最近.trim().slice(0, 60) : null;
};

const 行特征 = (行, i) => {
  const 围栏内 = (() => { let n = 0; for (let k = 0; k <= i; k++) if (是围栏(行[k])) n++; return n % 2 === 1; })();
  return { 表格: 是表格行(行[i]), 围栏内, 公式: /[=＝]/.test(行[i]) && /[A-Za-z0-9)]\s*[=＝]/.test(行[i]) };
};

/**
 * 四档判定，**互斥、按优先级**（缺陷①②③④ 逐条落到具体档）。
 * 📌 优先级顺序本身是阴性对照逼出来的（见下）：
 *   原写成「已订正 → 引述 → 方法论」，阴性对照用例 ② 立刻挂掉 ——
 *   订正文里**本来就会**出现 `原话`/`记下` 这些引述词。
 *   ⇒ **结构性事实（我在哪个章节）不能被措辞（我写了什么词）覆盖**：
 *     强标记（最硬的动作明示）> 方法论（最硬的结构位置）> 引述（最软的措辞）。
 */
const 分档 = (文件行, i) => {
  const 节 = 分节(文件行.行, i);
  const 邻 = 邻域行(文件行.行, i).join('\n');
  const m = 判标记(邻);
  const 节长 = 节.止 - 节.起 + 1;
  // 窗口 B：语义块。只用来交叉验证，不参与判档（见 语义块 的注释）
  const B = 语义块(文件行.行, i);
  const mB = 判标记(文件行.行.slice(B.起, B.止 + 1).join('\n'));
  const 宽 = { 块长: B.止 - B.起 + 1, 强: mB.强, 引述: mB.引述 };
  if (m.强.length) return { 档: '已订正', 因: `窗口A内强标记 ${JSON.stringify(m.强)}`, m, 节长, 宽 };
  if (立规节(文件行.行)) return { 档: '方法论', 因: `位于立规章节「${立规节(文件行.行)}」`, m, 节长, 宽 };
  if (m.引述.length) return { 档: '引述', 因: `窗口A内引述标记 ${JSON.stringify(m.引述)}`, m, 节长, 宽 };
  if (m.弱.length) return { 档: '仅弱标记', 因: `窗口A内弱标记 ${JSON.stringify(m.弱)}`, m, 节长, 宽 };
  return { 档: '正面陈述', 因: '窗口A内无强/引述标记，且非方法论章节', m, 节长, 宽 };
};

// ================= 阴性对照：4 条用例，各自必须判进指定档 =================
