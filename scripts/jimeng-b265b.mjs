/**
 * 批次 265b：把「缺订正标记」判定器的**四类系统性缺陷**量出来并修掉。
 *
 * 📌 起意（b265 的遗留）：b265 换用实测词表后把可行动清单从 `88` 压到 `15`，
 *   但人工逐条判读的结论是 **15/15 全是假阳性** —— 真缺口 `0`。
 *   🔴 这个 `0` **不能当成「手册干净了」**（立规 142 第三类：够不着 ≠ 干净）。
 *   本脚本要回答的是：**为什么 15 条全是假阳性？缺陷有哪几类、各覆盖多少？**
 *
 * 📌 逐条判读得到的**四类系统性缺陷**（不是「词表不够长」这一件事）：
 *
 *   缺陷① **邻域太小**：订正标记常在命中行**之外 4 行**。
 *     `help-and-shortcuts.md:252` 的订正标题在 **:248**，中间隔了 3 行块引用
 *     ⇒ `±3` 行的窗口**看不到**它。⇒ 改为**按分节切邻域**（到空行/标题/
 *     代码围栏/表格分隔行为止），而不是按固定行数。
 *
 *   缺陷② **词表漏了实际在用的订正记号**：`🔧`（旧记订正专用）在册却不在表内。
 *     实测 `🔧` 与「是错的」「已经过期」都是字面上的纠错措辞。
 *
 *   缺陷③ **不区分「引述旧说法」与「本手册当前断言」**：
 *     `30-concepts.md` 等处的「批次 N **记下**／**原话**／**此前**…」是在**复述**
 *     一条**已被推翻**的说法，附近没有订正标记是**正常的**。
 *
 *   缺陷④ **pattern 命中的是被台账采纳的正面结论本身**：
 *     如 `director-node.md:139` 的 `320×67`、`canvas-context.md:249` 的面板高公式、
 *     `organize-group-layout.md:492` 的 `224` —— 台账条目记的**就是**这些数字，
 *     手册正面陈述它们是**期望状态**。⇒ 命中 ≠ 该订正。
 *
 * 📌 **阴性对照是硬要求**（立规 132：报了「零」要能被证伪）：
 *   光有阳性对照（无标记→缺、有标记→已订正）不够 —— 它证明不了
 *   「引述/方法论/正面陈述」这三档**不会**被误判成缺口。
 *   本脚本在**内存里**造 `4` 条用例，四条**各自**必须判进指定档，全对才继续。
 *   **全程不写手册、不改台账。**
 *
 * 用法：node scripts/jimeng-b265b.mjs            （读数落盘 /tmp/b265b.json）
 *       node scripts/jimeng-b265b.mjs <文件名>   （只判该文件，定位用）
 */
