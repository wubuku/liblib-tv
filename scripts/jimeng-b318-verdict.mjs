/** 📌 同名项保留全部、按尺寸最接近配对 —— 🔴 批次 317 用 `map` 覆盖同名项是错的 */
function 配对(甲, 乙, 字段) {
  const 桶 = new Map();
  for (const y of 乙.清单[字段]) {
    if (!桶.has(y.号)) 桶.set(y.号, []);
    桶.get(y.号).push(y);
  }
  const 出 = [];
  for (const x of 甲.清单[字段]) {
    const c = 桶.get(x.号);
    if (!c) continue;
    const y = c.reduce((p, q) => (Math.abs(q.rect[2] - x.rect[2]) < Math.abs(p.rect[2] - x.rect[2]) ? q : p));
    if (x.rect[2] <= 0.5 || y.rect[2] <= 0.5) continue;
    const 宽比 = y.rect[2] / x.rect[2];
    const 缩比 = 乙.终点 / 甲.终点;
    出.push({
      号: x.号, 宽比: +宽比.toFixed(5), 缩比: +缩比.toFixed(5),
      偏离缩放: +((宽比 / 缩比 - 1) * 100).toFixed(2),
      偏离恒定: +((宽比 - 1) * 100).toFixed(3),
      甲宽: x.rect[2], 乙宽: y.rect[2],
      甲高: x.rect[3], 乙高: y.rect[3],
      高比: x.rect[3] > 0.5 && y.rect[3] > 0.5 ? +(y.rect[3] / x.rect[3]).toFixed(5) : null,
      pos: y.pos,
    });
  }
  return 出;
}

/** 📌 立规 197②：屏固定的判据是 C1 && C2 && C3 三条同时成立 */
const 是屏固定 = (r) => Math.abs(r.缩比 - 1) > 0.02
  && Math.abs(r.宽比 / r.缩比 - 1) > 0.02
  && Math.abs(r.宽比 - 1) <= 0.001;

function 段(甲键, 乙键, 字段) {
  const 甲 = 臂[甲键]; const 乙 = 臂[乙键];
  if (!甲 || !乙 || !甲.清单 || !乙.清单) return null;
  const 行 = 配对(甲, 乙, 字段);
  return {
    甲: 甲键, 乙: 乙键, 字段,
    甲落点: 甲.终点, 乙落点: 乙.终点,
    缩比: +(乙.终点 / 甲.终点).toFixed(5),
    可比数: 行.length,
    跟缩放: 行.filter((r) => Math.abs(r.宽比 / r.缩比 - 1) <= 0.02).length,
    不跟: 行.filter((r) => Math.abs(r.宽比 / r.缩比 - 1) > 0.02).length,
    屏固定: 行.filter(是屏固定),
    不跟的明细: 行.filter((r) => Math.abs(r.宽比 / r.缩比 - 1) > 0.02)
      .sort((a, b) => Math.abs(b.偏离恒定) - Math.abs(a.偏离恒定)).slice(0, 20),
  };
}

