/**
 * 批次 267：新建一个审计维度 —— **「未测声明」的时效性**。
 *
 * 📌 **起意（批次 266 顺手撞到的真缺口）**：
 *   批次 266 订正 `30-concepts.md:4836` 那句「取景模型现在完整地是」时，
 *   紧跟着的下一句逐字写着
 *   「⚠️ **时间线（W=1200）与图像（W=5120/9）的窄侧仍未测** ——
 *   按「屏上律与 W 无关」应预测落点 `= (w−412)/W`（本批**不测、不下结论**）」；
 *   而**往下 12 行**的批次 252 就是 `时间线 2` 与 `图片 b22-upload` 两族
 *   **`12/12` 逐字命中**，并明写「批次 251 那句『只验了两个 W 相同的族』的局限被解除」。
 *   ⇒ 🔴 **一句「仍未测」在同一页活了整个文件的后半段，没有任何订正标记。**
 *
 * 📌 **为什么这是个新维度、而不是批次 265 的重复**：
 *   265 查的是「**被推翻的结论**有没有订正标记」⇒ 判据来自**台账**。
 *   本批查的是「**自己写着『还没测』的句子，后来被测掉了**」⇒
 *   判据来自**文档自身的时序**，而这类句子**根本不在台账里**（它还没被推翻，它只是过期了）。
 *   ⇒ 🔴 **台账能覆盖的那一类，与这一类，是两回事。**
 *
 * 📌 **词表是量出来的，不是猜的**（逐词计数，落在下面「词频」里）。
 *
 * 📌 **对照是硬要求**（立规 143：报了数就要能被证伪）：
 *   ① **阳性对照**：人造一句「X 仍未测」＋ 后文一段把 X 测掉的记录
 *      ⇒ **必须**被判成「疑似过期」。
 *   ② **阴性对照**：人造一句「Y 仍未测」＋ 后文**没有**任何 Y 的测量记录
 *      ⇒ **必须**判不成「疑似过期」。
 *   两条都判对，判定器才算被验证过。**全程不写手册、不改台账。**
 *
 * 用法：node scripts/jimeng-b267.mjs      （读数落盘 /tmp/b267.json）
 */
import fs from 'node:fs';
import path from 'node:path';

const 手册根 = path.resolve('docs/user-manual/jimeng-canvas');
const OUT = process.env.B267_OUT || '/tmp/b267.json';
const log = (...a) => console.log(a.join(' '));

const 内容页前缀 = ['10-tasks/', '20-reference.md', '30-concepts.md', '90-troubleshooting.md', '00-quickstart.md'];
const 日志页名 = ['AUDIT.md', 'PROGRESS.md', 'SOURCE_OBSERVATIONS.md'];

const 走 = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
  const p = path.join(dir, d.name);
  if (d.isDirectory()) return d.name === 'node_modules' ? [] : 走(p);
  return d.name.endsWith('.md') ? [p] : [];
});
const 文件 = 走(手册根).map((f) => ({ 名: path.relative(手册根, f), 行: fs.readFileSync(f, 'utf8').split('\n') }));
const 全文 = 文件.map((f) => f.行.join('\n')).join('\n');

// ── ① 词频先量出来 ────────────────────────────────────────────────
const 候选词 = ['仍未测', '未测', '未复现', '没测过', '没测到', '一次都没测过', '不测', '未验',
  '未取到读数', '没有测', '尚未', '待测', '未测过', '没量到', '未覆盖', '未隔离', '未坐实'];
const 词频 = Object.fromEntries(候选词.map((w) => [w, 全文.split(w).length - 1]));

// ── ② 「未测声明」的行 + 它声称未测的对象 ─────────────────────────
// 📌 判「未测声明」用**窄口径**：行内出现未测词，且**同一句**里有被测对象
//   （节点名 / 尺寸 / 参数），否则像「机制未测，不编」这类**元陈述**会全部涌进来。
const 对象词 = ['时间线', '图像', '视频', '音频', '文本', '导演台', '主体', '节点', '窄侧', '宽侧',
  '横向', '纵向', '高度', '视口', '缩放', '封顶', '取景', '接缝', 'padding', '系数', '成因', '凹口', '轴'];
// 📌 **泛词**：这些词在全书到处都是，拿它们去找「后文证据」必然**证据数虚高**
//   （声明里写「仍未测」的是某个**具体量**，不是「节点」「缩放」这种大类）。
const 泛词 = new Set(['节点', '视口', '缩放', '文本', '音频', '视频', '图像', '图片', '时间线', '导演台', '主体', '取景']);
// 📌 **关闭词**：行里出现它们，说明这一行**本身就在宣布「这条已经关闭/作废」**，
//   不是在**断言一个缺口** ⇒ 混进「疑似过期」就是纯噪声
//   （实测：排除前 44 处里 majority 是这一类，例如「✅ 这条未验证项关闭」、
//    「🔴 批次 211 把『机制未验证』这条老账结清了」、`（销掉「未测」）`）。
const 关闭词 = ['关闭', '结清', '作废', '销掉', '不成立', '已修正', '推翻', '已被批次', '订正', '已撤'];
const 测量词 = ['逐字', '命中', '实测', '臂', '验过', '复现', '通过', '全绿', '符合', '对上', '读数为'];
const 未测词命中 = (l) => 候选词.filter((w) => l.includes(w));

const 声明 = [];
for (const f of 文件) {
  f.行.forEach((l, i) => {
    const 未 = 未测词命中(l);
    if (!未.length) return;
    const 对 = 对象词.filter((w) => l.includes(w));
    const 具体 = 对.filter((w) => !泛词.has(w));
    if (!具体.length) return;                  // 只有泛词 ⇒ 不知道在说什么，跳过
    if (关闭词.some((w) => l.includes(w))) return;  // 这一行本身在宣布关闭
    声明.push({
      文件: f.名, 行号: i + 1, 归类: 内容页前缀.some((p) => f.名.startsWith(p) || f.名 === p) ? '内容页'
        : 日志页名.includes(f.名) ? '日志页' : '其它',
      未测词: 未, 对象: 对, 具体对象: 具体, 片段: l.trim().slice(0, 130),
    });
  });
}

// ── ③ 时序检查：在**同文件更靠后**的正文里，这个对象有没有被测掉 ──
// 📌 判「有测量记录」要求**同时**出现对象词与测量词（两者在同一行）——
//   单看对象词会命中「继续说这件事」的叙述，单看测量词会命中别的事。
// 📌 阳性对照逼出来的**第一处**修法：
//   本手册最硬的「测掉了」证据恰恰是**读数表格行**
//   （如 `| 时间线 2 | 1200 | 512 | 0.0833333 | 0.0833333 | ✅ |`）——
//   而它**一个测量词都没有**（「逐字」「命中」都在表外的总结行里），
//   只按词表判会把**真缺口全部放过**，对照立刻挂掉。
//   ⇒ 补一条**结构性**判据：含对象、且是表格行、且数字够多 ⇒ 也算测量证据。
const 是表行 = (l) => { const t = l.trim(); return t.startsWith('|') && t.endsWith('|') && t.length > 1; };
const 数字格数 = (l) => (l.match(/\d/g) || []).length;
const 算测量证据 = (l) => (测量词.some((w) => l.includes(w)) || (是表行(l) && 数字格数(l) >= 6));

const 后文有测量 = (f, 起始行, 对象) => {
  const 证据 = [];
  for (let i = 起始行; i < f.行.length; i++) {
    const l = f.行[i];
    if (!对象.some((o) => l.includes(o))) continue;
    if (!算测量证据(l)) continue;
    // 📌 排除「订正/推翻」句本身：那些是在**说这件事过期了**，不是**证据**
    if (/订正|推翻|已被批次|不成立/.test(l)) continue;
    证据.push({ 行号: i + 1, 片段: l.trim().slice(0, 110) });
  }
  return 证据;
};

const 判定 = [];
for (const d of 声明) {
  const f = 文件.find((x) => x.名 === d.文件);
  const 证据 = 后文有测量(f, d.行号, d.对象);
  判定.push({ ...d, 后文测量证据数: 证据.length, 后文证据: 证据.slice(0, 3) });
}
const 疑似 = 判定.filter((x) => x.后文测量证据数 > 0);

// ── ④ 对照（阳性 + 阴性，落在判定器本身上） ────────────────────────
const 对照 = (() => {
  const 造 = (行) => ({ 名: '<内存用例>', 行 });
  // ① 阳性：前句说「窄侧仍未测」，后文有「逐字命中」的测量记录 ⇒ 必须判「疑似过期」
  const 正 = 造([
    '⚠️ 时间线与图像的窄侧仍未测 —— 本批不测、不下结论。',
    '',
    '#### 批次 999',
    '| 时间线 2 | 1200 | 512 | 0.0833333 | 0.0833333 | ✅ |',
    '🔴 12/12 命中，零例外。',
  ]);
  // ② 阴性：前句说「音频凹口成因仍未测」，后文**没有**任何测量记录 ⇒ 必须判「不像过期」
  const 负 = 造([
    '⚠️ 音频凹口的成因仍未测，本批不编。',
    '',
    '#### 批次 999',
    '音频凹口只出现在 1212–1230 这段视口宽里。',
    '这条观察本身没有任何逐字读数支撑。',
  ]);
  const 检 = (f) => {
    const d = [];
    f.行.forEach((l, i) => {
      const 未 = 未测词命中(l); if (!未.length) return;
      const 对 = 对象词.filter((w) => l.includes(w));
      const 具体 = 对.filter((w) => !泛词.has(w));
      if (!具体.length) return;
      if (关闭词.some((w) => l.includes(w))) return;
      d.push({ i, 对 });
    });
    const 过期 = d.some((x) => 后文有测量(f, x.i, x.对).length > 0);
    return 过期;
  };
  const r1 = 检(正), r2 = 检(负);
  return {
    用例1_阳性: { 说明: '前句「窄侧仍未测」＋后文逐字命中 ⇒ 应判疑似过期', 实得: r1, 通过: r1 === true },
    用例2_阴性: { 说明: '前句「成因仍未测」＋后文无任何测量 ⇒ 不应判疑似过期', 实得: r2, 通过: r2 === false },
    通过: r1 === true && r2 === false,
  };
})();

log('=== 对照（证明判定器能杀也能放过）===');
log(`  ① 阳性 ${对照.用例1_阳性.通过 ? '✅' : '❌'}  实得「疑似过期=${对照.用例1_阳性.实得}」`);
log(`  ② 阴性 ${对照.用例2_阴性.通过 ? '✅' : '❌'}  实得「疑似过期=${对照.用例2_阴性.实得}」`);
if (!对照.通过) { log('🔴 判定器自检没过，后面结果不可用'); process.exit(4); }

const out = {
  轮次: 'b267', 问: '「未测声明」的时效性：哪些句子后来被测掉了却没订正？',
  词频, 对照, 声明数: 声明.length, 判定数: 判定.length, 疑似过期数: 疑似.length, 疑似: [], 汇总: {},
};
const 内容页声明 = 判定.filter((x) => x.归类 === '内容页');
out.汇总 = {
  声明总数: 声明.length,
  内容页声明: 内容页声明.length,
  日志页声明: 判定.filter((x) => x.归类 === '日志页').length,
  内容页疑似过期: 内容页声明.filter((x) => x.后文测量证据数 > 0).length,
};
out.疑似 = 内容页声明.filter((x) => x.后文测量证据数 > 0);

log('\n=== 词频（量出来的）===');
log(JSON.stringify(词频, null, 1));
log(`\n=== 「未测声明」共 ${声明.length} 处（内容页 ${内容页声明.length} 处）===`);
log(`    其中疑似过期 ${out.疑似.length} 处\n`);
for (const x of out.疑似) {
  log(`  🔴 ${x.文件}:${x.行号}｜具体对象 ${JSON.stringify(x.具体对象)}｜后文证据 ${x.后文测量证据数} 条`);
  log(`     声明：${x.片段}`);
  for (const e of x.后文证据) log(`     ↳ ${e.行号}: ${e.片段}`);
}

log('\n=== 📋 全部内容页「未测声明」明细（供人工判读，判定器不替它们下结论）===');
for (const x of 内容页声明) {
  log(`  ${x.后文测量证据数 ? '⚠️' : '　'} ${x.文件}:${x.行号}｜${JSON.stringify(x.具体对象)}｜${x.片段.slice(0, 88)}`);
}

fs.writeFileSync(OUT, JSON.stringify(out, null, 1));
log(`\n写入 ${OUT}`);
process.exit(0);
