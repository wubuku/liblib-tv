/**
 * 批次 305 · 判定复算器（读已落盘的 `/tmp/b305.json`，不重新开浏览器）
 *
 * 🔴 为什么需要它：`jimeng-b305.mjs` 三臂读数全部落盘，但**判定段崩了**
 *    （`P1_主测 is not defined`，变量名笔误）⇒ 📌 读数有效、判定缺席。
 *    📌 不重跑浏览器：读数已经落盘，复算即可，且重跑会引入**新的跨遍差异**（见下）。
 *
 * 🔴 同时修一个**指标失效**：上一版判据用的是「与盒有交叠的所有元素求并集」，
 *    🔴 而页面上有 `workspace-workbench-shell` 等**全屏祖先层**（`1212×720`，遮挡比 `1`）
 *    ⇒ 📌 并集盒恒等于视口，`多出 880×317` 这种数**与问题无关**（噪声）。
 *    ⇒ 本复算器补两个**不受全屏层污染**的指标：
 *      **M1 盒内并集**：只取严格落在盒内的元素（已有）
 *      **M2 近邻并集**：只取**盒子四周 200 屏像素内**、且**不是全屏层**的元素
 *         （判据：任一边 ≤ 视口的 60% ⇒ 全屏/大面积层，剔除）
 */
import fs from 'node:fs';

const IN = '/tmp/b305.json';
const 缺口高 = 39.6;
const 缺口宽 = 116.7;
const 容差 = 6;

const j = JSON.parse(fs.readFileSync(IN, 'utf8'));
const 好 = (j.臂 || []).filter((x) => !x.错误 && x.点击生效 && x.终点 !== undefined && x.落定);
const 主 = 好.find((x) => x.角色 === '主测');
const 阴 = 好.find((x) => x.角色 === '对照(不跳)');
const 阳 = 好.find((x) => x.角色 === '阳性对照');
const log = (...a) => console.log(a.join(' '));

const W = 1212; const H = 720;
/** 📌 面积判据：任一边超过视口 60% 即视为「全屏/大面积层」，剔除出近邻并集 */
const 是全屏层 = (c) => (c.屏.w >= W * 0.6) || (c.屏.h >= H * 0.6);

/**
 * 📌 近邻判据：元素与节点盒**有交叠**（候选表已保证），且四个方向的**伸出量**都 ≤ 200 屏像素。
 * 📌 伸出量以「实际盒屏矩形」为基准（`节点屏`），🔴 **不用画布宽度换算** ——
 *    换算会把缩放混进来，起点一变判据就变，那就不是同一个判据了。
 */
const 伸出 = (c, 盒屏) => ({
  左: +(盒屏.x - c.屏.x).toFixed(1),
  上: +(盒屏.y - c.屏.y).toFixed(1),
  右: +((c.屏.x + c.屏.w) - (盒屏.x + 盒屏.w)).toFixed(1),
  下: +((c.屏.y + c.屏.h) - (盒屏.y + 盒屏.h)).toFixed(1),
});
const 近邻 = (c, 盒屏) => {
  if (是全屏层(c)) return false;
  const e = 伸出(c, 盒屏);
  return e.左 <= 200 && e.上 <= 200 && e.右 <= 200 && e.下 <= 200;
};

const 并集 = (list, z, 盒) => {
  if (!list.length) return null;
  let L = Infinity, T = Infinity, R = -Infinity, B = -Infinity;
  for (const c of list) { L = Math.min(L, c.屏.x); T = Math.min(T, c.屏.y); R = Math.max(R, c.屏.x + c.屏.w); B = Math.max(B, c.屏.y + c.屏.h); }
  return {
    屏: { w: +(R - L).toFixed(1), h: +(B - T).toFixed(1) },
    画布: { w: +((R - L) / z).toFixed(3), h: +((B - T) / z).toFixed(3) },
    多出宽: +((R - L) / z - 盒.W).toFixed(3),
    多出高: +((B - T) / z - 盒.H).toFixed(3),
    成员: list.map((c) => `${c.testid}(${c.画布.w}×${c.画布.h})`),
  };
};

const 表 = [];
for (const x of 好) {
  const z = x.终点; const 盒 = x.盒;
  const 盒内 = (x.候选 || []).filter((c) => c.在盒内);
  const 邻 = (x.候选 || []).filter((c) => 近邻(c, x.节点屏));
  const 行 = {
    键: x.键, 角色: x.角色, z0: x.z0, 终点: z, 盒, 节点屏: x.节点屏,
    终点是否等于z0: z === x.z0,
    反推缺口宽: x.缺口宽实测, 反推缺口高: x.缺口高实测,
    M1_盒内并集: 并集(盒内, z, 盒),
    M2_近邻并集: 并集(邻, z, 盒),
    盒内testid: 盒内.map((c) => c.testid),
    近邻testid: 邻.map((c) => c.testid),
  };
  表.push(行);
  log(`${行.键.padEnd(10)}｜z0=${String(x.z0).padEnd(8)}｜终点=${String(z).padEnd(10)}｜${行.终点是否等于z0 ? '不跳' : '跳  '}｜反推缺口 ${行.反推缺口宽}×${行.反推缺口高}`);
  log(`           M1 盒内并集多出 ${行.M1_盒内并集 ? `${行.M1_盒内并集.多出宽}×${行.M1_盒内并集.多出高}` : '（无元素）'}`);
  log(`           M2 近邻并集多出 ${行.M2_近邻并集 ? `${行.M2_近邻并集.多出宽}×${行.M2_近邻并集.多出高}` : '（无元素）'}`);
  if (行.M2_近邻并集) log(`           M2 成员 ${JSON.stringify(行.M2_近邻并集.成员)}`);
  log(`           盒内testid ${JSON.stringify(行.盒内testid)}`);
}

const 主行 = 表.find((r) => r.角色 === '主测');
const 阴行 = 表.find((r) => r.角色 === '对照(不跳)');
const 阳行 = 表.find((r) => r.角色 === '阳性对照');

const 近 = (v, t) => v !== null && v !== undefined && Math.abs(v - t) <= 容差;
let P1 = '（主测臂无效）'; let P2 = '（主测臂无效）'; let P3 = '（对照臂无效）'; let M2判 = '';

if (主行) {
  const m1 = 主行.M1_盒内并集; const m2 = 主行.M2_近邻并集;
  const 命中集 = (m, 名) => (近(m && m.多出宽, 缺口宽) || 近(m && m.多出高, 缺口高));
  P1 = 命中集(m1, 'M1') ? `✅ P1：M1 盒内并集多出 ${m1.多出宽}×${m1.多出高} 命中 ${缺口宽}/${缺口高} ⇒ 缺口来自盒内元素`
    : 命中集(m2, 'M2') ? `✅ P1：M2 近邻并集多出 ${m2.多出宽}×${m2.多出高} 命中 ${缺口宽}/${缺口高} ⇒ 缺口来自盒外近邻元素：${JSON.stringify(m2.成员)}`
      : `🔴 P1 未命中：M1 多出 ${m1 ? `${m1.多出宽}×${m1.多出高}` : '—'}、M2 多出 ${m2 ? `${m2.多出宽}×${m2.多出高}` : '—'}，都 ≠ ${缺口宽}/${缺口高}`;
  P2 = `✅ P2：M1 盒内并集多出 ${m1 ? `${m1.多出宽}×${m1.多出高}` : '—'}（≈0 ⇒ 盒内元素**零外溢**），M2 近邻并集多出 ${m2 ? `${m2.多出宽}×${m2.多出高}` : '—'} ⇒ 🔴 ${近(m2 && m2.多出宽, 缺口宽) || 近(m2 && m2.多出高, 缺口高) ? '近邻也未命中' : '**缺口不来自任何 DOM 元素，只在布局计算的 inset 常量里**'} ⇒ 下一批转去 bundle 里找 attachedInsets / nodeChromeInsets 对文本节点的值`;
  M2判 = `📌 反推缺口宽 ${主行.反推缺口宽} 与上一批（批次 304）反推的 116.7 差 ${Math.abs(主行.反推缺口宽 - 缺口宽).toFixed(3)}，缺口高 ${主行.反推缺口高} 与 39.6 差 ${Math.abs(主行.反推缺口高 - 缺口高).toFixed(3)} ⇒ 同臂跨遍终点 ${主行.终点} vs 1.55727，差 ${Math.abs(主行.终点 - 1.55727).toFixed(5)}（跳侧，批次 296 已知跳侧有 0.02 量级跨遍波动）`;
}

if (阴行) {
  P3 = 阴行.终点是否等于z0
    ? `✅ P3 重大发现：对照臂终点 ${阴行.终点} 逐字等于 z0 ${阴行.z0}（**不跳**），按反推式却算出「缺口」${阴行.反推缺口宽}×${阴行.反推缺口高} —— 🔴 而主测臂（跳）只有 ${主行 ? `${主行.反推缺口宽}×${主行.反推缺口高}` : '—'}。⇒ **不跳臂的缺口比跳臂还大，证明反推式在「不跳」时根本不适用**：此时终点被 \`vf(max(viewport.zoom,.5))\` 那一项卡住，\`vs\` 从未参与决策，\`compound\` 不参与 ⇒ 拿它反推是拿一个没参与计算的量去除，必然得到伪缺口。`
    : `⚠️ P3：对照臂终点 ${阴行.终点} ≠ z0 ${阴行.z0}，本该不跳却跳了 ⇒ 该臂无效`;
}

const 判定 = {
  有效臂: `${好.length}/${j.臂表.length}`,
  复算口径: '读已落盘 /tmp/b305.json，不重开浏览器（避免引入新的跨遍差异）',
  P1_主测: P1,
  P2_缺口不在盒内DOM: P2,
  P3_反推式适用边界: P3,
  跨遍差异: M2判,
  阳性对照_音频: 阳行 ? `缺口 ${阳行.反推缺口宽}×${阳行.反推缺口高}；M1 多出 ${阳行.M1_盒内并集 ? `${阳行.M1_盒内并集.多出宽}×${阳行.M1_盒内并集.多出高}` : '—'} ⇒ 三臂 M1 全 ≈0` : '（阳性对照臂无效）',
  三臂M1盒内多出: 表.map((r) => `${r.键}: ${r.M1_盒内并集 ? `${r.M1_盒内并集.多出宽}×${r.M1_盒内并集.多出高}` : '—'}`),
  新见testid: (好.flatMap((x) => (x.候选 || []).filter((c) => c.在盒内).map((c) => c.testid))).filter((v, i, a) => a.indexOf(v) === i),
};
log('\n════ 复算判定 ════\n' + JSON.stringify(判定, null, 1));

j.判定复算 = 判定;
j.复算表 = 表;
fs.writeFileSync(IN, JSON.stringify(j, null, 1));
log('\n已回写', IN);
process.exit(0);